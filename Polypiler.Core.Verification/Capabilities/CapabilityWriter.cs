using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Text;
using System.Text.Json.Nodes;
using Polypiler.Core.Verification.Gates;
using Polypiler.Core.Verification.Manifests;

namespace Polypiler.Core.Verification.Capabilities;

/// <summary>
/// The two files of a <see cref="CapabilityReport"/>: the JSON written as the manifest is
/// (<see cref="CanonicalJson"/>: two-space indentation, LF, one final line break) and the Markdown
/// computed from the same pairs, so that the Markdown of a committed JSON file can be checked against it.
/// </summary>
internal static class CapabilityWriter {

  /// <summary>The first line of the Markdown file.</summary>
  public const string MarkdownHeader = "<!-- generated by polypiler-tooling report capabilities; do not edit -->";

  /// <summary>What each state means, in the order of PRD §23.6.</summary>
  private static readonly string[] _meanings = [
    "no gate record proves anything yet",
    "the frontend read the source without an error",
    "the source became IR that passed the verifier",
    "at least one pattern was recognized (optional)",
    "every applied rewrite has an accepted proof class (optional)",
    "the IR is legal for the target",
    "the target code was written",
    "the target code was built",
    "the target code ran",
    "the target code agreed with an independent oracle",
    "the target code met its benchmark"
  ];

  /// <summary>The JSON text of a report.</summary>
  public static string Json(CapabilityReport report) {
    var root = new JsonObject {
      ["schemaVersion"] = CapabilityReport.SchemaVersion,
      ["generatedFrom"] = new JsonObject {
        ["commit"] = report.Commit,
        ["gateRecords"] = report.GateRecords
      },
      ["states"] = new JsonArray([.. Enum.GetValues<GateState>().Select(state => (JsonNode)GateStates.Name(state))]),
      ["pairs"] = new JsonArray([.. report.Pairs.Select(pair => (JsonNode)new JsonObject {
        ["from"] = pair.From,
        ["sourceProfile"] = pair.SourceProfile,
        ["to"] = pair.To,
        ["targetProfile"] = pair.TargetProfile,
        ["state"] = GateStates.Name(pair.State),
        ["fixtures"] = pair.Fixtures,
        ["evidence"] = pair.Evidence,
        ["limitations"] = new JsonArray([.. pair.Limitations.Select(limitation => (JsonNode)new JsonObject {
          ["construct"] = limitation.Construct,
          ["diagnostic"] = limitation.Diagnostic
        })])
      })])
    };
    return CanonicalJson.Serialize(root) + "\n";
  }

  /// <summary>The Markdown text of a report.</summary>
  public static string Markdown(CapabilityReport report) {
    var text = new StringBuilder();
    text.Append(MarkdownHeader).Append('\n');
    text.Append("# Capabilities\n\n");
    text.Append(CultureInfo.InvariantCulture, $"Generated by `polypiler-tooling report capabilities` from commit `{report.Commit}` and {Counted(report.GateRecords, "gate record")}. ");
    text.Append("A row is a source profile, a column a target `language/profile`, and a cell the state the gate records prove for that pair: ");
    text.Append("the lowest state among the pair's fixtures, `planned` without a valid record. Nothing else can raise a cell. ");
    text.Append("[`capabilities.json`](capabilities.json) holds the same pairs with their evidence.\n");

    if (report.Pairs.Count == 0)
      text.Append("\nNo source profile and target profile are specified under `spec/`, so the report has no pair.\n");

    foreach (var language in report.Pairs.GroupBy(pair => pair.From)) {
      var columns = language.Select(pair => (pair.To, pair.TargetProfile)).Distinct().ToList();
      text.Append(CultureInfo.InvariantCulture, $"\n## {Cell(language.Key)}\n\n");
      text.Append("| Source profile |");
      foreach (var (to, profile) in columns)
        text.Append(CultureInfo.InvariantCulture, $" {Cell(to + "/" + profile)} |");
      text.Append("\n| --- |");
      text.Append(string.Concat(Enumerable.Repeat(" --- |", columns.Count)));
      text.Append('\n');

      var profiles = language.GroupBy(pair => pair.SourceProfile).ToList();
      foreach (var profile in profiles) {
        text.Append(CultureInfo.InvariantCulture, $"| {Cell(profile.Key)} |");
        foreach (var (to, target) in columns)
          text.Append(CultureInfo.InvariantCulture, $" {(profile.FirstOrDefault(pair => pair.To == to && pair.TargetProfile == target) is { } pair ? GateStates.Name(pair.State) : "—")} |");
        text.Append('\n');
      }

      var limited = profiles.Where(profile => profile.First().Limitations.Count > 0).ToList();
      if (limited.Count == 0)
        continue;

      text.Append("\nKnown limitations, the constructs a source profile diagnoses instead of translating:\n\n");
      foreach (var profile in limited)
        text.Append(CultureInfo.InvariantCulture, $"- `{profile.Key}`: {string.Join("; ", profile.First().Limitations.Select(Limitation))}\n");
    }

    text.Append("\n## States\n\n");
    foreach (var state in Enum.GetValues<GateState>())
      text.Append(CultureInfo.InvariantCulture, $"{(int)state + 1}. `{GateStates.Name(state)}`: {_meanings[(int)state]}\n");

    return text.ToString();
  }

  private static string Limitation(CapabilityLimitation limitation)
    => limitation.Diagnostic.Length == 0 ? Inline(limitation.Construct) : $"{Inline(limitation.Construct)} ({limitation.Diagnostic})";

  /// <summary>A text inside a table cell: a vertical bar escaped.</summary>
  private static string Cell(string text) => text.Replace("|", "\\|", StringComparison.Ordinal);

  /// <summary>A text inside a list item: line breaks read as spaces.</summary>
  private static string Inline(string text) => text.ReplaceLineEndings(" ");

  private static string Counted(int count, string noun) => count == 1 ? $"1 {noun}" : $"{count.ToString(CultureInfo.InvariantCulture)} {noun}s";

}
