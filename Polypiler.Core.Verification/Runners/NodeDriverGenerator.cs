using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using System.Text.Json;
using System.Text.Json.Nodes;
using Polypiler.Core.Verification.Images;

namespace Polypiler.Core.Verification.Runners;

/// <summary>
/// Generates <c>__driver.mjs</c>, the program that calls one export of a JavaScript module on node: the
/// constants of the export (entry module, module system, dotted export path, signature) in front of
/// the driver and image codec of <c>Runners/Node/images.mjs.txt</c>. The driver loads the entry once
/// (<c>import()</c>, or <c>createRequire</c> for CommonJS), and per input line decodes the arguments,
/// calls the export inside <c>try</c>/<c>catch</c> with standard output guarded, and prints the output
/// image or the trap line.
/// </summary>
public static class NodeDriverGenerator {

  /// <summary>The file name of the driver in the run.</summary>
  public const string FileName = "__driver.mjs";

  /// <summary>The exit code of a protocol error.</summary>
  public const int ProtocolExitCode = 2;

  /// <summary>The exit code of an export that does not exist or is not a function.</summary>
  public const int MissingExportExitCode = 3;

  private const string ResourceName = "Polypiler.Core.Verification.Runners.Node.images.mjs.txt";

  private static readonly Lazy<string> _template = new(() => {
    using var stream = typeof(NodeDriverGenerator).Assembly.GetManifestResourceStream(ResourceName)!;
    using var reader = new StreamReader(stream, Encoding.UTF8);
    return reader.ReadToEnd().ReplaceLineEndings("\n");
  });

  /// <summary>The driver and image codec every driver shares, without the constants of an export.</summary>
  public static string Template => _template.Value;

  /// <summary>The source of the driver of one export.</summary>
  /// <param name="entry">The entry module, relative to the run's directory with <c>/</c> between folders.</param>
  /// <param name="export">The export, a dotted path into the module's exports such as <c>OpCodes.RotL32</c>.</param>
  /// <param name="signature">The images the export takes and gives; JavaScript declares none, so it is always the caller's.</param>
  /// <returns>The text of <c>__driver.mjs</c>.</returns>
  /// <exception cref="ArgumentException">The export is empty or has an empty segment.</exception>
  public static string Generate(string entry, string export, CallSignature signature) {
    ArgumentException.ThrowIfNullOrWhiteSpace(entry);
    return Generate(entry, IsCommonJs(entry, null), export, signature);
  }

  private static string Generate(string entry, bool commonJs, string export, CallSignature signature) {
    ArgumentException.ThrowIfNullOrWhiteSpace(export);
    ArgumentNullException.ThrowIfNull(signature);
    if (export.Split('.').Any(segment => segment.Length == 0))
      throw new ArgumentException($"the export '{export}' has an empty segment", nameof(export));

    var parameters = new JsonArray([.. signature.Parameters.Select(parameter => (JsonNode)new JsonObject {
      ["n"] = parameter.Name,
      ["m"] = Spelling(parameter.Mode),
      ["t"] = Describe(parameter.Type)
    })]);
    var described = new JsonObject { ["p"] = parameters, ["r"] = signature.Result is { } result ? Describe(result) : null };
    var text = new StringBuilder();
    text.Append("// <auto-generated/> The Polypiler driver of ").Append(export.Replace('\n', ' ')).Append(".\n");
    text.Append("const ENTRY = ").Append(JsonSerializer.Serialize("./" + entry)).Append(";\n");
    text.Append("const COMMONJS = ").Append(commonJs ? "true" : "false").Append(";\n");
    text.Append("const EXPORT = ").Append(JsonSerializer.Serialize(export)).Append(";\n");
    text.Append("const SIGNATURE = ").Append(described.ToJsonString()).Append(";\n\n");
    return text.Append(Template).ToString();
  }

  /// <summary>The source of the driver, with the module system read from the run's <c>package.json</c> as well.</summary>
  /// <param name="files">The run's files, which name the entry module.</param>
  /// <param name="export">The export.</param>
  /// <param name="signature">The signature.</param>
  /// <returns>The text of <c>__driver.mjs</c>.</returns>
  /// <exception cref="ArgumentException">There is no entry module, or the export is empty.</exception>
  public static string Generate(IReadOnlyDictionary<string, ReadOnlyMemory<byte>> files, string export, CallSignature signature) {
    var entry = Entry(files);
    return Generate(entry, IsCommonJs(entry, PackageType(files)), export, signature);
  }

  /// <summary>
  /// The entry module of a run: <c>main</c> or a string <c>exports</c> of <c>package.json</c>, else
  /// <c>index.mjs</c>, <c>index.cjs</c>, <c>index.js</c> in that order, else the one JavaScript file
  /// when there is exactly one.
  /// </summary>
  /// <param name="files">The files, by name relative to the run's directory.</param>
  /// <returns>The entry, relative to the directory, without a leading <c>./</c>.</returns>
  /// <exception cref="ArgumentException">No rule names an entry that exists.</exception>
  public static string Entry(IReadOnlyDictionary<string, ReadOnlyMemory<byte>> files) {
    ArgumentNullException.ThrowIfNull(files);
    if (Package(files) is { } package) {
      var named = package["exports"] is JsonValue exports && exports.TryGetValue<string>(out var path) ? path
        : package["main"] is JsonValue main && main.TryGetValue<string>(out var mainPath) ? mainPath
        : null;
      if (named is not null) {
        var normal = named.StartsWith("./", StringComparison.Ordinal) ? named[2..] : named;
        return files.ContainsKey(normal) ? normal : throw new ArgumentException($"package.json names the entry '{named}', which is not among the files", nameof(files));
      }
    }

    foreach (var index in new[] { "index.mjs", "index.cjs", "index.js" })
      if (files.ContainsKey(index))
        return index;

    var scripts = files.Keys.Where(IsScript).ToList();
    return scripts.Count == 1 ? scripts[0] : throw new ArgumentException($"there is no entry module among {scripts.Count} JavaScript file(s): no package.json entry and no index.mjs, index.cjs or index.js", nameof(files));
  }

  /// <summary>Whether a file is a JavaScript module node checks: <c>.js</c>, <c>.mjs</c> or <c>.cjs</c>.</summary>
  /// <param name="name">The file name.</param>
  public static bool IsScript(string name) {
    ArgumentNullException.ThrowIfNull(name);
    return name.EndsWith(".js", StringComparison.Ordinal) || name.EndsWith(".mjs", StringComparison.Ordinal) || name.EndsWith(".cjs", StringComparison.Ordinal);
  }

  /// <summary>Whether node loads a module as CommonJS: <c>.cjs</c>, or <c>.js</c> unless <c>package.json</c> says <c>"type": "module"</c>.</summary>
  private static bool IsCommonJs(string entry, string? packageType)
    => entry.EndsWith(".cjs", StringComparison.Ordinal) || entry.EndsWith(".js", StringComparison.Ordinal) && packageType != "module";

  private static string? PackageType(IReadOnlyDictionary<string, ReadOnlyMemory<byte>> files)
    => Package(files)?["type"] is JsonValue type && type.TryGetValue<string>(out var text) ? text : null;

  private static JsonObject? Package(IReadOnlyDictionary<string, ReadOnlyMemory<byte>> files) {
    if (!files.TryGetValue("package.json", out var bytes))
      return null;

    try {
      return JsonNode.Parse(bytes.Span) as JsonObject ?? throw new ArgumentException("package.json is not a JSON object", nameof(files));
    } catch (JsonException exception) {
      throw new ArgumentException("package.json is not JSON: " + exception.Message, nameof(files), exception);
    }
  }

  private static string Spelling(ParameterMode mode) => mode switch {
    ParameterMode.In => "in",
    ParameterMode.InOut => "inout",
    _ => "out"
  };

  /// <summary>
  /// An image type as the driver reads it: <c>k</c> the kind, <c>n</c> the name of a scalar, <c>w</c>
  /// its width, <c>s</c> whether it is signed, <c>e</c> the element, <c>f</c> the fields.
  /// </summary>
  public static JsonObject Describe(ImageType type) {
    ArgumentNullException.ThrowIfNull(type);
    return type.Kind switch {
      ImageKind.Integer => new() { ["k"] = "int", ["n"] = type.ToString(), ["w"] = type.Width, ["s"] = type.Signed },
      ImageKind.Float => new() { ["k"] = "float", ["n"] = type.ToString(), ["w"] = type.Width },
      ImageKind.Boolean => new() { ["k"] = "bool" },
      ImageKind.Char16 => new() { ["k"] = "char16" },
      ImageKind.BigInt => new() { ["k"] = "bigint" },
      ImageKind.Bytes => new() { ["k"] = "bytes" },
      ImageKind.Utf8 => new() { ["k"] = "utf8" },
      ImageKind.Utf16 => new() { ["k"] = "utf16" },
      ImageKind.Sequence => new() { ["k"] = "seq", ["e"] = Describe(type.Element!) },
      ImageKind.Optional => new() { ["k"] = "opt", ["e"] = Describe(type.Element!) },
      ImageKind.Enum => new() { ["k"] = "enum", ["e"] = Describe(type.Element!) },
      ImageKind.Record => new() { ["k"] = "record", ["f"] = new JsonArray([.. type.Fields.Select(field => (JsonNode)new JsonArray(field.Name, Describe(field.Type)))]) },
      ImageKind.Tuple => new() { ["k"] = "tuple", ["f"] = new JsonArray([.. type.Fields.Select(field => (JsonNode)Describe(field.Type))]) },
      ImageKind.Union => new() { ["k"] = "union", ["f"] = new JsonArray([.. type.Fields.Select(field => (JsonNode)Describe(field.Type))]) },
      _ => new() { ["k"] = "null" }
    };
  }

}
