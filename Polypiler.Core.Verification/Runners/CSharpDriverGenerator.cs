using Polypiler.Core.Verification.Images;

namespace Polypiler.Core.Verification.Runners;

/// <summary>The target framework, language version and arithmetic a C# profile builds with.</summary>
/// <param name="Name">The profile, such as <c>csharp/net10</c>.</param>
/// <param name="TargetFramework">The target framework moniker, such as <c>net10.0</c>.</param>
/// <param name="LanguageVersion">The C# language version, such as <c>14</c>.</param>
/// <param name="CheckedArithmetic">Whether integer arithmetic outside <c>unchecked</c> traps: <c>CheckForOverflowUnderflow</c>.</param>
public sealed record CSharpProfile(string Name, string TargetFramework, string LanguageVersion, bool CheckedArithmetic) {

  /// <summary>The default profile: .NET 10, C# 14, unchecked arithmetic.</summary>
  public static CSharpProfile Net10 { get; } = new("csharp/net10", "net10.0", "14", false);

  /// <summary>The profiles the runner builds for, by name; other frameworks extend this table.</summary>
  public static IReadOnlyDictionary<string, CSharpProfile> Known { get; } = new Dictionary<string, CSharpProfile>(StringComparer.Ordinal) {
    [Net10.Name] = Net10,
    ["csharp/net10-checked"] = Net10 with { Name = "csharp/net10-checked", CheckedArithmetic = true }
  };

}

/// <summary>
/// Generates the C# driver of one export: <c>Driver.csproj</c>, an SDK-style console project, and
/// <c>Driver.cs</c>, whose <c>Main</c> reads one input image in hexadecimal per line of standard input,
/// decodes the arguments with straight-line reads at a running offset (<c>BinaryPrimitives</c>, no
/// reflection, no boxing), calls the method directly inside <c>try</c>/<c>catch</c>, and prints the
/// output image in lower-case hexadecimal or the trap line <c>!&lt;class&gt; &lt;exception type&gt;</c>.
/// An input it cannot read, an export it was not built for, and a function under test that writes to
/// standard output end it with exit code 2 and the reason on standard error.
/// </summary>
public static class CSharpDriverGenerator {

  /// <summary>The project file of the driver.</summary>
  public const string ProjectFile = "Driver.csproj";

  /// <summary>The source file of the driver.</summary>
  public const string SourceFile = "Driver.cs";

  /// <summary>The assembly the build writes into <c>out</c>.</summary>
  public const string Assembly = "out/Driver.dll";

  /// <summary>The exit code of a protocol error.</summary>
  public const int ProtocolExitCode = 2;

  /// <summary>The project file for a profile.</summary>
  /// <param name="profile">The profile.</param>
  /// <returns>The text of <c>Driver.csproj</c>.</returns>
  public static string Project(CSharpProfile profile) {
    ArgumentNullException.ThrowIfNull(profile);
    return "<Project Sdk=\"Microsoft.NET.Sdk\">\n"
      + "  <PropertyGroup>\n"
      + "    <OutputType>Exe</OutputType>\n"
      + $"    <TargetFramework>{profile.TargetFramework}</TargetFramework>\n"
      + $"    <LangVersion>{profile.LanguageVersion}</LangVersion>\n"
      + "    <AssemblyName>Driver</AssemblyName>\n"
      + "    <RootNamespace>Driver</RootNamespace>\n"
      + "    <StartupObject>PolypilerDriver.Program</StartupObject>\n"
      + "    <Nullable>enable</Nullable>\n"
      + "    <ImplicitUsings>disable</ImplicitUsings>\n"
      + "    <TreatWarningsAsErrors>true</TreatWarningsAsErrors>\n"
      + "    <Deterministic>true</Deterministic>\n"
      + $"    <CheckForOverflowUnderflow>{(profile.CheckedArithmetic ? "true" : "false")}</CheckForOverflowUnderflow>\n"
      + "    <AllowUnsafeBlocks>false</AllowUnsafeBlocks>\n"
      + "    <NuGetAudit>false</NuGetAudit>\n"
      + "    <ImportDirectoryBuildProps>false</ImportDirectoryBuildProps>\n"
      + "    <ImportDirectoryBuildTargets>false</ImportDirectoryBuildTargets>\n"
      + "  </PropertyGroup>\n"
      + "</Project>\n";
  }

  /// <summary>The source of the driver for one export.</summary>
  /// <param name="binding">The export bound to its declaration.</param>
  /// <returns>The text of <c>Driver.cs</c>.</returns>
  public static string Generate(CSharpExportBinding binding) {
    ArgumentNullException.ThrowIfNull(binding);
    var text = new StringBuilder();
    text.Append("// <auto-generated/> The Polypiler driver of ").Append(binding.Export).Append(".\n");
    text.Append("#nullable enable\n\nnamespace PolypilerDriver;\n\n");
    text.Append("internal static class Program {\n\n");
    text.Append("  private static int Main(string[] args) {\n");
    text.Append("    if (args.Length != 1 || args[0] != ").Append(Literal(binding.Export)).Append(")\n");
    text.Append("      return Protocol(\"the export '\" + (args.Length > 0 ? args[0] : \"\") + \"' does not exist; the driver calls ").Append(Escaped(binding.Export)).Append("\");\n\n");
    text.Append("    var stdout = new global::System.IO.StreamWriter(global::System.Console.OpenStandardOutput(), new global::System.Text.UTF8Encoding(false)) { NewLine = \"\\n\" };\n");
    text.Append("    var captured = new global::System.IO.StringWriter();\n");
    text.Append("    global::System.Console.SetOut(captured);\n");
    text.Append("    using var stdin = new global::System.IO.StreamReader(global::System.Console.OpenStandardInput());\n");
    text.Append("    var number = 0;\n");
    text.Append("    while (stdin.ReadLine() is { } line) {\n");
    text.Append("      ++number;\n");
    text.Append("      string answer;\n");
    text.Append("      try {\n");
    text.Append("        answer = Call(global::System.Convert.FromHexString(line));\n");
    text.Append("      } catch (global::System.FormatException) {\n");
    text.Append("        return Protocol(\"line \" + number + \" is not an image in hexadecimal\");\n");
    text.Append("      } catch (ProtocolException error) {\n");
    text.Append("        return Protocol(\"line \" + number + \": \" + error.Message);\n");
    text.Append("      }\n\n");
    text.Append("      if (captured.GetStringBuilder().Length > 0)\n");
    text.Append("        return Protocol(\"call \" + number + \": the function under test wrote to standard output\");\n\n");
    text.Append("      stdout.WriteLine(answer);\n");
    text.Append("      stdout.Flush();\n");
    text.Append("    }\n\n");
    text.Append("    return 0;\n");
    text.Append("  }\n\n");
    text.Append("  private static int Protocol(string reason) {\n");
    text.Append("    global::System.Console.Error.WriteLine(reason);\n");
    text.Append("    return ").Append(ProtocolExitCode.ToString(CultureInfo.InvariantCulture)).Append(";\n");
    text.Append("  }\n\n");
    text.Append("  private static string Trap(global::System.Exception exception) {\n");
    text.Append("    var name = exception.GetType().Name;\n");
    text.Append("    var trap = name switch {\n");
    foreach (var (exception, kind) in CSharpTraps.Table)
      text.Append("      ").Append(Literal(exception)).Append(" => ").Append(Literal(new TrapClass(kind).ToString())).Append(",\n");
    text.Append("      _ => \"other:\" + name\n");
    text.Append("    };\n");
    text.Append("    return \"!\" + trap + \" \" + name;\n");
    text.Append("  }\n\n");
    Call(text, binding);
    text.Append("}\n\n");
    text.Append(Runtime);
    return text.ToString();
  }

  private static void Call(StringBuilder text, CSharpExportBinding binding) {
    const string Pad = "    ";
    var names = new Names();
    text.Append("  private static string Call(byte[] input) {\n");
    text.Append(Pad).Append("var r = new ImageReader(input);\n");
    var arguments = new List<string>();
    for (var index = 0; index < binding.Parameters.Count; ++index) {
      var parameter = binding.Parameters[index];
      var local = "a" + index.ToString(CultureInfo.InvariantCulture);
      if (parameter.Mode == ParameterMode.Out)
        text.Append(Pad).Append(parameter.Shape.TypeName).Append(' ').Append(local).Append(";\n");
      else
        text.Append(Pad).Append(parameter.Shape.TypeName).Append(' ').Append(local).Append(" = ").Append(Read(parameter.Shape)).Append(";\n");

      arguments.Add(parameter.Passing switch {
        CSharpPassing.Ref => "ref " + local,
        CSharpPassing.Out => "out " + local,
        CSharpPassing.In => "in " + local,
        _ => local
      });
    }

    text.Append(Pad).Append("r.End();\n");
    var call = $"{binding.Method}({string.Join(", ", arguments)})";
    if (binding.Result is { } result)
      text.Append(Pad).Append(result.TypeName).Append(" result;\n");

    text.Append(Pad).Append("try {\n");
    text.Append(Pad).Append("  ").Append(binding.Result is null ? call : "result = " + call).Append(";\n");
    text.Append(Pad).Append("} catch (global::System.Exception exception) {\n");
    text.Append(Pad).Append("  return Trap(exception);\n");
    text.Append(Pad).Append("}\n\n");
    text.Append(Pad).Append("var w = new ImageWriter();\n");
    text.Append(Pad).Append("try {\n");
    if (binding.Result is { } returned)
      Write(text, Pad + "  ", returned, "result", names);

    for (var index = 0; index < binding.Parameters.Count; ++index)
      if (binding.Parameters[index].Mode != ParameterMode.In)
        Write(text, Pad + "  ", binding.Parameters[index].Shape, "a" + index.ToString(CultureInfo.InvariantCulture), names);

    text.Append(Pad).Append("} catch (ResultTypeException exception) {\n");
    text.Append(Pad).Append("  return \"!result-type \" + exception.Message;\n");
    text.Append(Pad).Append("}\n\n");
    text.Append(Pad).Append("return w.Hex();\n");
    text.Append("  }\n\n");
  }

  /// <summary>The expression that reads a value of a shape at the reader's offset.</summary>
  private static string Read(CSharpShape shape) => shape.Container switch {
    CSharpContainer.Scalar => $"r.{Method(shape.Image)}()",
    CSharpContainer.Enum => $"({shape.TypeName})r.{Method(shape.Element!.Image)}()",
    CSharpContainer.String => "r.Utf16()",
    CSharpContainer.Array or CSharpContainer.Span or CSharpContainer.ReadOnlySpan => shape.Image.Kind == ImageKind.Bytes
      ? "r.Bytes()"
      : $"r.Array<{shape.Element!.TypeName}>(() => {Read(shape.Element)})",
    CSharpContainer.Optional => $"r.Present() ? {Read(shape.Element!)} : null",
    CSharpContainer.Tuple => $"({string.Join(", ", shape.Members.Select(member => Read(member.Shape)))})",
    _ => $"new {shape.TypeName} {{ {string.Join(", ", shape.Members.Select(member => $"{member.Name} = {Read(member.Shape)}"))} }}"
  };

  /// <summary>The statements that append a value of a shape to the writer.</summary>
  private static void Write(StringBuilder text, string pad, CSharpShape shape, string value, Names names) {
    switch (shape.Container) {
      case CSharpContainer.Scalar:
        text.Append(pad).Append(CultureInfo.InvariantCulture, $"w.{Method(shape.Image)}({value});\n");
        return;
      case CSharpContainer.Enum:
        text.Append(pad).Append(CultureInfo.InvariantCulture, $"w.{Method(shape.Element!.Image)}(({shape.Element.TypeName}){value});\n");
        return;
      case CSharpContainer.String:
        text.Append(pad).Append(CultureInfo.InvariantCulture, $"w.Utf16({value});\n");
        return;
      case CSharpContainer.Array or CSharpContainer.Span or CSharpContainer.ReadOnlySpan: {
        var source = shape.Container == CSharpContainer.Array ? $"w.NotNull({value})" : value;
        if (shape.Image.Kind == ImageKind.Bytes) {
          text.Append(pad).Append(CultureInfo.InvariantCulture, $"w.Bytes({source});\n");
          return;
        }

        var sequence = names.Next("s");
        var element = names.Next("e");
        text.Append(pad).Append("{\n");
        text.Append(pad).Append(CultureInfo.InvariantCulture, $"  var {sequence} = {source};\n");
        text.Append(pad).Append(CultureInfo.InvariantCulture, $"  w.Count({sequence}.Length);\n");
        text.Append(pad).Append(CultureInfo.InvariantCulture, $"  foreach (var {element} in {sequence}) {{\n");
        Write(text, pad + "    ", shape.Element!, element, names);
        text.Append(pad).Append("  }\n");
        text.Append(pad).Append("}\n");
        return;
      }
      case CSharpContainer.Optional: {
        var present = names.Next("p");
        text.Append(pad).Append(CultureInfo.InvariantCulture, $"if ({value} is {{ }} {present}) {{\n");
        text.Append(pad).Append("  w.U8(1);\n");
        Write(text, pad + "  ", shape.Element!, present, names);
        text.Append(pad).Append("} else {\n");
        text.Append(pad).Append("  w.U8(0);\n");
        text.Append(pad).Append("}\n");
        return;
      }
      default:
        foreach (var member in shape.Members)
          Write(text, pad, member.Shape, value + "." + member.Name, names);
        return;
    }
  }

  /// <summary>The reader's and writer's method of a scalar image type: its name with a capital, <c>I32</c>.</summary>
  private static string Method(ImageType type) {
    var name = type.ToString();
    return char.ToUpperInvariant(name[0]) + name[1..];
  }

  private static string Literal(string text) => "\"" + Escaped(text) + "\"";

  private static string Escaped(string text) => text.Replace("\\", "\\\\", StringComparison.Ordinal).Replace("\"", "\\\"", StringComparison.Ordinal);

  /// <summary>Fresh local names, numbered per prefix.</summary>
  private sealed class Names {

    private int _next;

    public string Next(string prefix) => prefix + (this._next++).ToString(CultureInfo.InvariantCulture);

  }

  /// <summary>The reader and writer of the image encoding of <see cref="ImageCodec"/>, as part of every driver.</summary>
  private const string Runtime = """
    internal sealed class ProtocolException(string message) : global::System.Exception(message);

    internal sealed class ResultTypeException(string message) : global::System.Exception(message);

    internal sealed class ImageReader(byte[] bytes) {

      private int _at;

      private global::System.ReadOnlySpan<byte> Take(int count) {
        if (count < 0 || bytes.Length - this._at < count)
          throw new ProtocolException("the input image ends inside a value");

        var span = new global::System.ReadOnlySpan<byte>(bytes, this._at, count);
        this._at += count;
        return span;
      }

      public void End() {
        if (this._at != bytes.Length)
          throw new ProtocolException("the input image has " + (bytes.Length - this._at) + " byte(s) after the last argument");
      }

      public sbyte I8() => (sbyte)this.Take(1)[0];

      public byte U8() => this.Take(1)[0];

      public short I16() => global::System.Buffers.Binary.BinaryPrimitives.ReadInt16LittleEndian(this.Take(2));

      public ushort U16() => global::System.Buffers.Binary.BinaryPrimitives.ReadUInt16LittleEndian(this.Take(2));

      public int I32() => global::System.Buffers.Binary.BinaryPrimitives.ReadInt32LittleEndian(this.Take(4));

      public uint U32() => global::System.Buffers.Binary.BinaryPrimitives.ReadUInt32LittleEndian(this.Take(4));

      public long I64() => global::System.Buffers.Binary.BinaryPrimitives.ReadInt64LittleEndian(this.Take(8));

      public ulong U64() => global::System.Buffers.Binary.BinaryPrimitives.ReadUInt64LittleEndian(this.Take(8));

      public float F32() => global::System.BitConverter.Int32BitsToSingle(this.I32());

      public double F64() => global::System.BitConverter.Int64BitsToDouble(this.I64());

      public char Char16() => (char)this.U16();

      public bool Bool() => this.U8() switch {
        0 => false,
        1 => true,
        _ => throw new ProtocolException("a bool is 00 or 01")
      };

      public bool Present() => this.Bool();

      public int Count() {
        var count = this.U32();
        if (count > (uint)(bytes.Length - this._at))
          throw new ProtocolException("a count of " + count + " exceeds the rest of the input image");

        return (int)count;
      }

      public byte[] Bytes() => this.Take(this.Count()).ToArray();

      public string Utf16() {
        var units = new char[this.Count()];
        for (var index = 0; index < units.Length; ++index)
          units[index] = this.Char16();

        return new string(units);
      }

      public T[] Array<T>(global::System.Func<T> element) {
        var values = new T[this.Count()];
        for (var index = 0; index < values.Length; ++index)
          values[index] = element();

        return values;
      }

    }

    internal sealed class ImageWriter {

      private readonly global::System.Collections.Generic.List<byte> _bytes = new();

      private void Put(global::System.ReadOnlySpan<byte> bytes) => global::System.Collections.Generic.CollectionExtensions.AddRange(this._bytes, bytes);

      public void I8(sbyte value) => this._bytes.Add((byte)value);

      public void U8(byte value) => this._bytes.Add(value);

      public void I16(short value) {
        global::System.Span<byte> bytes = stackalloc byte[2];
        global::System.Buffers.Binary.BinaryPrimitives.WriteInt16LittleEndian(bytes, value);
        this.Put(bytes);
      }

      public void U16(ushort value) {
        global::System.Span<byte> bytes = stackalloc byte[2];
        global::System.Buffers.Binary.BinaryPrimitives.WriteUInt16LittleEndian(bytes, value);
        this.Put(bytes);
      }

      public void I32(int value) {
        global::System.Span<byte> bytes = stackalloc byte[4];
        global::System.Buffers.Binary.BinaryPrimitives.WriteInt32LittleEndian(bytes, value);
        this.Put(bytes);
      }

      public void U32(uint value) {
        global::System.Span<byte> bytes = stackalloc byte[4];
        global::System.Buffers.Binary.BinaryPrimitives.WriteUInt32LittleEndian(bytes, value);
        this.Put(bytes);
      }

      public void I64(long value) {
        global::System.Span<byte> bytes = stackalloc byte[8];
        global::System.Buffers.Binary.BinaryPrimitives.WriteInt64LittleEndian(bytes, value);
        this.Put(bytes);
      }

      public void U64(ulong value) {
        global::System.Span<byte> bytes = stackalloc byte[8];
        global::System.Buffers.Binary.BinaryPrimitives.WriteUInt64LittleEndian(bytes, value);
        this.Put(bytes);
      }

      public void F32(float value) => this.I32(global::System.BitConverter.SingleToInt32Bits(value));

      public void F64(double value) => this.I64(global::System.BitConverter.DoubleToInt64Bits(value));

      public void Char16(char value) => this.U16(value);

      public void Bool(bool value) => this._bytes.Add(value ? (byte)1 : (byte)0);

      public void Count(int count) => this.U32((uint)count);

      public void Bytes(global::System.ReadOnlySpan<byte> value) {
        this.Count(value.Length);
        this.Put(value);
      }

      public void Utf16(string? value) {
        var text = this.NotNull(value);
        this.Count(text.Length);
        foreach (var unit in text)
          this.U16(unit);
      }

      public T NotNull<T>(T? value) where T : class => value ?? throw new ResultTypeException("NullResult");

      public string Hex() => global::System.Convert.ToHexStringLower(global::System.Runtime.InteropServices.CollectionsMarshal.AsSpan(this._bytes));

    }

    """;

}
