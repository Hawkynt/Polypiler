/// <summary>JVMS <c>newarray</c> primitive element type codes (JVMS §6.5).</summary>
internal enum JvmArrayType : byte {
  Boolean = 4,
  Char = 5,
  Float = 6,
  Double = 7,
  Byte = 8,
  Short = 9,
  Int = 10,
  Long = 11
}

/// <summary>
/// A JVMS §4.7.4 verification type used for operand-stack tracking and <c>StackMapTable</c> frames.
/// </summary>
internal readonly record struct VType(byte Tag, ushort ClassIndex = 0) {

  public const byte IntegerTag = 1;
  public const byte FloatTag = 2;
  public const byte DoubleTag = 3;
  public const byte LongTag = 4;
  public const byte NullTag = 5;
  public const byte ObjectTag = 7;

  public static VType Int => new(IntegerTag);
  public static VType Float => new(FloatTag);
  public static VType Double => new(DoubleTag);
  public static VType Long => new(LongTag);
  public static VType Null => new(NullTag);
  public static VType Object(ushort classCpIndex) => new(ObjectTag, classCpIndex);

  /// <summary>Number of JVM operand-stack words / local-variable slots occupied (2 for long/double, 1 otherwise).</summary>
  public int Slots => this.Tag is DoubleTag or LongTag ? 2 : 1;

}
