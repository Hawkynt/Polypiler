using System;
using System.IO;
using System.Linq;
using System.Text.Json.Nodes;
using NUnit.Framework;
using Polypiler.Prototype.Testing;
using Polypiler.Tests.Acceptance.Prototype;
using Polypiler.Tests.Acceptance.Steps;
using Polypiler.Tests.Acceptance.Support;
using Polypiler.Tooling.Spec;
using Reqnroll;

namespace Polypiler.Tests.Acceptance.Permutation;

/// <summary>
/// The steps of <c>tests/features/permutation/perm-spec.feature</c>. The scenario's workspace stands in
/// for the repository: it holds the permutations schema, and the real <c>polypiler-tooling</c>
/// executable imports a copy of <c>tests/fixtures/bitperm</c> and validates what is placed under
/// <c>spec/permutations</c>. A document named without a copy step is the repository's checked-in one.
/// </summary>
[Binding, Scope(Feature = "spec/permutations holds BitPerm's mappings, grammars and cost presets")]
public sealed class PermSpecSteps(ScenarioWorkspace workspace, CommandLog log) {

  private const string Fixtures = "tests/fixtures/bitperm";

  private static readonly string _root = PrototypeFixture.RepositoryRoot;

  private JsonObject? _body;

  private static string RepositoryFile(string path) => Path.Combine(_root, path.Replace('/', Path.DirectorySeparatorChar));

  private static JsonObject BodyOf(string path)
    => (JsonObject)SpecDocument.Parse(path["spec/".Length..], File.ReadAllText(RepositoryFile(path))).Body!;

  /// <summary>Puts the family's schema where the tool looks for it from the workspace.</summary>
  [BeforeScenario]
  public void CopySchema() => workspace.Copy(RepositoryFile("spec/schemas/permutations.schema.json"), "spec/schemas/permutations.schema.json");

  private void CopyFixtures() {
    var source = RepositoryFile(Fixtures);
    foreach (var file in Directory.EnumerateFiles(source, "*", SearchOption.AllDirectories))
      workspace.Copy(file, $"{Fixtures}/{Path.GetRelativePath(source, file).Replace(Path.DirectorySeparatorChar, '/')}");
  }

  /// <summary>Copies the fixtures and the seed document into the workspace and runs the importer's command line there.</summary>
  [Given("^the documents generated by " + StepText.Quoted + "$")]
  public void Generated(string line) {
    this.CopyFixtures();
    workspace.Copy(RepositoryFile("spec/permutations/mappings/reverse8.yaml"), "spec/permutations/mappings/reverse8.yaml");
    var words = CommandLine.Split(line).ToArray();
    Assert.That(words[0], Is.EqualTo("polypiler-tooling"));
    var import = log.Add(Toolchain.Tooling(workspace.Path, words[1..]));
    Assert.That(import.ExitCode, Is.Zero, import.Output);
  }

  /// <summary>Reads a checked-in document of the repository.</summary>
  [Given("^the document " + StepText.Quoted + "$")]
  public void Document(string path) => this._body = BodyOf(path);

  /// <summary>Checks the cycles of one primitive of the cost document.</summary>
  [Then("^primitive " + StepText.Quoted + @" has cycles (\d+)$")]
  public void PrimitiveCycles(string primitive, int cycles) {
    var cost = this._body!["costs"]!.AsArray().Single(entry => (string?)entry!["primitive"] == primitive)!;
    Assert.That((long)cost["cycles"]!, Is.EqualTo(cycles));
  }

  /// <summary>Checks that the cost document lists none of the primitives.</summary>
  [Then(@"^it lists no cost for ((?:""[^""]+""(?:, | or )?)+)$")]
  public void NoCostFor(string list) {
    var absent = list.Split('"').Where((_, index) => index % 2 == 1).ToArray();
    Assert.That(absent, Has.Length.EqualTo(5));
    var listed = this._body!["costs"]!.AsArray().Select(entry => (string)entry!["primitive"]!);
    Assert.That(listed, Has.None.AnyOf(absent));
  }

  /// <summary>Checks every generated cost document of the repository for BitPerm's "unavailable" figure.</summary>
  [Then(@"^no cost in any generated document has cycles (\d+)$")]
  public void NoCostWith(int cycles) {
    var documents = Directory.GetFiles(RepositoryFile("spec/permutations/costs"), "bitperm-*.yaml");
    Assert.That(documents, Has.Length.EqualTo(25));
    var all = documents.SelectMany(file => BodyOf("spec/permutations/costs/" + Path.GetFileName(file))["costs"]!.AsArray()).Select(cost => (long)cost!["cycles"]!);
    Assert.That(all, Has.None.EqualTo(cycles));
  }

  /// <summary>Places the checked-in document in the workspace with one vector output changed.</summary>
  [Given("^" + StepText.Quoted + " with the vector output for input " + StepText.Quoted + " changed from " + StepText.Quoted + " to " + StepText.Quoted + "$")]
  public void Tampered(string path, string input, string from, string to) {
    var original = $"{{input: \"{input}\", output: \"{from}\"}}";
    var text = File.ReadAllText(RepositoryFile(path));
    Assert.That(text, Does.Contain(original));
    workspace.Write(path, text.Replace(original, $"{{input: \"{input}\", output: \"{to}\"}}", StringComparison.Ordinal));
  }

  /// <summary>Copies the fixtures into the workspace and adds a cost key to one preset of the copy.</summary>
  [Given("^a copy of \"presets.json\" in which preset " + StepText.Quoted + " has the additional cost key " + StepText.Quoted + "$")]
  public void AdditionalCostKey(string preset, string key) {
    this.CopyFixtures();
    var path = workspace.Resolve($"{Fixtures}/presets.json");
    var presets = JsonNode.Parse(File.ReadAllText(path))!.AsArray();
    presets.Single(entry => (string?)entry!["id"] == preset)!["costs"]![key] = 1;
    File.WriteAllText(path, presets.ToJsonString());
  }

  /// <summary>Runs the importer on the workspace's fixtures.</summary>
  [When("^I run the importer on it$")]
  public void RunImporter() => log.Add(Toolchain.Tooling(workspace.Path, "permutations", "import-bitperm", "--fixtures", Fixtures, "--out", "spec/permutations"));

  /// <summary>Checks the last line of standard output.</summary>
  [Then("^the last output line is " + StepText.Quoted + "$")]
  public void LastOutputLine(string text)
    => Assert.That(CommandSteps.WithoutTrailingNewline(log.Last.Stdout).Split('\n')[^1].TrimEnd('\r'), Is.EqualTo(StepText.Unescape(text)), log.Last.Output);

}
