  /// <summary><c>x + y</c> as a double and its exact error, when <c>|x| &gt;= |y|</c> or <c>x</c> is zero.</summary>
  private static double InverseHyperbolicFastTwoSum(double x, double y, double[] low) {
    var s = x + y;
    var z = s - x;
    low[0] = y - z;
    return s;
  }

  /// <summary>The sum of two double-doubles, the high parts added exactly whatever their magnitude.</summary>
  private static double InverseHyperbolicAddDD(double xh, double xl, double ch, double cl, double[] low) {
    var s = xh + ch;
    var d = s - xh;
    low[0] = ((ch - d) + (xh + (d - s))) + (xl + cl);
    return s;
  }

  /// <summary>The product of two double-doubles, normalized.</summary>
  private static double InverseHyperbolicMulDDAccurate(double xh, double xl, double ch, double cl, double[] low) {
    var ahlh = ch * xl;
    var alhh = cl * xh;
    var ahhh = ch * xh;
    var ahhl = Math.FusedMultiplyAdd(ch, xh, -ahhh);
    ahhl += alhh + ahlh;
    return InverseHyperbolicFastTwoSum(ahhh, ahhl, low);
  }

  /// <summary>The product of a double-double and a double, normalized.</summary>
  private static double InverseHyperbolicMulDDD(double xh, double xl, double ch, double[] low) {
    var ahlh = ch * xl;
    var ahhh = ch * xh;
    var ahhl = Math.FusedMultiplyAdd(ch, xh, -ahhh);
    ahhl += ahlh;
    return InverseHyperbolicFastTwoSum(ahhh, ahhl, low);
  }

  /// <summary>
  /// <c>log(1 + x)/2</c> of the double-double <c>(xh, xl)</c> of the accurate logarithm: the terms of
  /// x^4 to x^6 in double, those of x to x^3 by Horner's rule in double-double.
  /// </summary>
  private static double InverseHyperbolicRefineLog1P(double xh, double xl, double[] low) {
    var sl = xh * (_inverseHyperbolicRefineLow[0] + xh * (_inverseHyperbolicRefineLow[1] + xh * _inverseHyperbolicRefineLow[2]));
    var k = _inverseHyperbolicRefineHigh.Length / 2 - 1;
    var ch = InverseHyperbolicFastTwoSum(_inverseHyperbolicRefineHigh[2 * k], sl, low);
    var cl = low[0] + _inverseHyperbolicRefineHigh[2 * k + 1];
    while (--k >= 0) {
      ch = InverseHyperbolicMulDDAccurate(xh, xl, ch, cl, low);
      cl = low[0];
      ch = InverseHyperbolicFastTwoSum(_inverseHyperbolicRefineHigh[2 * k], ch, low);
      cl += low[0] + _inverseHyperbolicRefineHigh[2 * k + 1];
    }

    return InverseHyperbolicMulDDAccurate(xh, xl, ch, cl, low);
  }

  /// <summary>
  /// The middle part of a sum <c>h + m + l</c> moved by one unit towards <c>l</c> when it is a power
  /// of two, so that adding it to the high part cannot round as if the sum were halfway.
  /// </summary>
  private static double InverseHyperbolicOffPowerOfTwo(double m, double l) {
    var t = (ulong)BitConverter.DoubleToInt64Bits(m);
    if ((t & ~0UL >> 12) != 0)
      return m;

    var w = (ulong)BitConverter.DoubleToInt64Bits(l);
    if ((w ^ t) >> 63 != 0)
      t--;
    else
      t++;

    return BitConverter.Int64BitsToDouble((long)t);
  }

  /// <summary>
  /// The correctly rounded result for an argument the accurate path cannot round, found by binary
  /// search for <c>|x|</c> in <paramref name="rows"/> rows of the database from <paramref name="first"/>
  /// on and given the sign of <c>x</c>; <paramref name="f"/> for any other argument.
  /// </summary>
  private static double InverseHyperbolicDatabase(int first, int rows, double x, double f) {
    var ax = Math.Abs(x);
    var a = first;
    var b = first + rows - 1;
    var m = (a + b) / 2;
    while (a <= b) {
      if (_inverseHyperbolicDatabase[3 * m] < ax) {
        a = m + 1;
      } else if (_inverseHyperbolicDatabase[3 * m] == ax) {
        var sign = CopySign(1, x);
        return sign * _inverseHyperbolicDatabase[3 * m + 1] + sign * _inverseHyperbolicDatabase[3 * m + 2];
      } else {
        b = m - 1;
      }

      m = (a + b) / 2;
    }

    return f;
  }

