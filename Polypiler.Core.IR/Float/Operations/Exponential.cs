/// <summary>
/// The exponential functions <c>e^x</c>, <c>2^x</c>, <c>10^x</c> and <c>e^x - 1</c>, correctly
/// rounded in both formats. They are converted from CORE-MATH (MIT); see
/// <c>THIRD-PARTY-NOTICE.CORE-MATH.Exponential.txt</c>. Every one reduces its argument to
/// <c>2^(k/2^12) * 2^r</c> or <c>2^(k/2^6) * 2^r</c> with a small <c>r</c>, evaluates a short
/// polynomial and checks whether an error bound decides the rounding; where it does not, a slower
/// path in double-double arithmetic decides it, and a short list of exceptional arguments settles
/// the few cases that one leaves open. This part holds the double-double arithmetic and the tables
/// the four share.
/// </summary>
