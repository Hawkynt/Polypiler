  /// <summary>
  /// The sum of two numbers with <c>|x| &gt;= |y|</c> (or <c>x</c> zero), exactly as a rounded sum
  /// and its error: returns <c>x + y</c> and writes the error into <c>error[0]</c>.
  /// </summary>
  private static double ExpFastTwoSum(double x, double y, double[] error) {
    var s = x + y;
    var z = s - x;
    error[0] = y - z;
    return s;
  }

  /// <summary>The sum of two double-double numbers; the low part goes into <c>low[0]</c>.</summary>
  private static double ExpFastSum(double xh, double xl, double yh, double yl, double[] low) {
    var sh = ExpFastTwoSum(xh, yh, low);
    low[0] = (xl + yl) + low[0];
    return sh;
  }

  /// <summary>The product of two double-double numbers; the low part goes into <c>low[0]</c>.</summary>
  private static double ExpMulDD(double xh, double xl, double ch, double cl, double[] low) {
    var h = ch * xh;
    low[0] = (ch * xl + cl * xh) + Math.FusedMultiplyAdd(ch, xh, -h);
    return h;
  }

  /// <summary>The product of a double and a double-double number; the low part goes into <c>low[0]</c>.</summary>
  private static double ExpMulDDD(double a, double bh, double bl, double[] low) {
    var h = a * bh;
    low[0] = a * bl + Math.FusedMultiplyAdd(a, bh, -h);
    return h;
  }

