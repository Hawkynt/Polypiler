  /// <summary>
  /// The decimal logarithm, correctly rounded: the natural logarithm to about 2^-68 from a table of
  /// 363 reciprocals, multiplied by 1 / ln(10) in double-double; the exact 128-bit computation when
  /// that cannot decide the rounding. A power of ten gives its exponent exactly.
  /// </summary>
  /// <param name="x">The number.</param>
  /// <returns><c>log10 x</c>; negative infinity for a zero, NaN for a negative number or a NaN.</returns>
  public static double Log10(double x) {
    var bits = (ulong)BitConverter.DoubleToInt64Bits(x);
    var e = (int)(bits >> 52) - 0x3ff;
    if (e >= 0x400 || e == -0x3ff) {
      // +infinity or a NaN of either sign.
      if (e == 0x400 || (e == 0xc00 && x != double.NegativeInfinity))
        return x + x;

      if (x <= 0.0)
        return x < 0 ? double.NaN : double.NegativeInfinity;

      // A subnormal number, scaled into the normal range.
      bits = (ulong)BitConverter.DoubleToInt64Bits(x * 4503599627370496.0); // 0x1p52
      e = (int)(bits >> 52) - 0x3ff - 52;
    }

    // 10^n for 0 <= n <= 22 gives n exactly; the exponent of x selects the one candidate.
    var n = unchecked(0x267cfa2u * ((uint)e + 1u)) >> 27;
    if (bits == (ulong)BitConverter.DoubleToInt64Bits(_log10Powers[(int)n]))
      return n;

    // x = 2^e * y with y in [1/sqrt(2), sqrt(2)).
    var m = bits & 0xfffffffffffffUL;
    var c = m >= 0x6a09e667f3bcdUL ? 1 : 0;
    var y = BitConverter.Int64BitsToDouble((long)(((0x3ffUL - (ulong)c) << 52) + m));
    e += c;
    var i = (int)((0x10000000000000UL + m) >> (43 + c));
    var r = _log10Inverse[i - 362];
    var l1 = _log10InverseLog[2 * (i - 362)];
    var l2 = _log10InverseLog[2 * (i - 362) + 1];
    var z = Math.FusedMultiplyAdd(r, y, -1.0);

    // P(z) - z for |z| < 0.00212097167968735; the polynomial is the one of the natural logarithm.
    var z2 = z * z;
    var p45 = Math.FusedMultiplyAdd(_logPolynomial[5], z, _logPolynomial[4]);
    var p23 = Math.FusedMultiplyAdd(_logPolynomial[3], z, _logPolynomial[2]);
    var ph = Math.FusedMultiplyAdd(p45, z2, p23);
    ph = Math.FusedMultiplyAdd(ph, z, _logPolynomial[1]);
    ph *= z2;

    // Add e * log(2); log2High is a multiple of 2^-42, so e * log2High + l1 is exact.
    const double Log2High = 0.6931471805598903; // 0x1.62e42fefa38p-1
    const double Log2Low = 5.497923018708371E-14; // 0x1.ef35793c7673p-45
    double ee = e;
    var a = Math.FusedMultiplyAdd(ee, Log2High, l1);
    var h = a + z;
    var l = z - (h - a);
    l = ph + (l + l2);
    l = Math.FusedMultiplyAdd(ee, Log2Low, l);

    // Multiply by 1 / ln(10), leaving out l * InverseLn10Low.
    const double InverseLn10High = 0.4342944819032518; // 0x1.bcb7b1526e50ep-2
    const double InverseLn10Low = 1.098319650216765E-17; // 0x1.95355baaafad3p-57
    var hi = h * InverseLn10High;
    var s = Math.FusedMultiplyAdd(h, InverseLn10High, -hi);
    var t = Math.FusedMultiplyAdd(l, InverseLn10High, s);
    var lo = Math.FusedMultiplyAdd(h, InverseLn10Low, t);

    // The largest absolute error of the approximation hi + lo.
    const double Error = 1.7205356741102976E-21; // 0x1.04p-69
    var left = hi + (lo - Error);
    var right = hi + (lo + Error);
    if (left == right)
      return left;

    var result = LogDintLog(LogDintFromDouble(x));
    return LogDintToDouble(LogDintMultiply(LogDint(0xde5bd8a937287195UL, 0x355baaafad33dc32UL, -2, 0), result));
  }

  /// <summary>
  /// The decimal logarithm of a <c>float</c>, correctly rounded: a table of 65 reciprocals and a
  /// polynomial of degree 3, refined with one of degree 7 when the first cannot decide the rounding.
  /// A power of ten gives its exponent exactly.
  /// </summary>
  /// <param name="x">The number.</param>
  /// <returns><c>log10 x</c>; negative infinity for a zero, NaN for a negative number or a NaN.</returns>
  public static float Log10F(float x) {
    var ux = (uint)BitConverter.SingleToInt32Bits(x);
    if (ux >= 0x7f800000u)
      return LogSpecialF(x);

    // 10^n for 0 <= n <= 10 gives n exactly.
    if (ux == _log10PowersF[(ux >> 24) & 0xf]) {
      var je = (uint)(((int)ux >> 23) - 126);
      je = unchecked(je * 0x4d104d4u) >> 28;
      return je;
    }

    if (ux < 0x00800000u) {
      if (ux == 0u)
        return LogSpecialF(x);

      // A subnormal number, normalized.
      var n = System.Numerics.BitOperations.LeadingZeroCount(ux) - 8;
      ux <<= n;
      ux -= (uint)(n << 23);
    }

    var e = ((int)ux >> 23) - 127;
    var m = (long)(ux & ((1u << 23) - 1));
    var j = (int)((m + (1 << (23 - 7))) >> (23 - 6));
    var tz = BitConverter.Int64BitsToDouble((m << (52 - 23)) | (0x3ffL << 52));
    var z = tz * _logReciprocalF[j] - 1;
    var z2 = z * z;
    const double Log10Of2 = 0.3010299956639812; // 0x1.34413509f79ffp-2
    const double Log10Of2High = 0.30102999566398125; // 0x1.34413509f7ap-2
    const double Log10Of2Low = -5.8314879359043E-17; // -0x1.0cee0ed4ca7e9p-54
    var r = ((e * Log10Of2 + _log10ReciprocalLogF[j]) + z * _log10FastF[0]) + z2 * (_log10FastF[1] + z * _log10FastF[2]);
    var ub = (float)r;
    var lb = (float)(r + 9.802997302799099E-11); // 0x1.af23fp-34
    if (ub != lb) {
      var f = z * ((_log10PolynomialF[0] + z * _log10PolynomialF[1]) + z2 * ((_log10PolynomialF[2] + z * _log10PolynomialF[3])
        + z2 * (_log10PolynomialF[4] + z * _log10PolynomialF[5] + z2 * _log10PolynomialF[6])));
      f += Log10Of2Low * e;
      f += _log10ReciprocalLogF[j] - _log10ReciprocalLogF[0];
      var el = e * Log10Of2High;
      r = el + f;
      ub = (float)r;
      // A result whose last 28 bits are zero may be a halfway case: add the error of the sum.
      if ((BitConverter.DoubleToInt64Bits(r) & ((1L << 28) - 1)) == 0) {
        var dr = (el - r) + f;
        r += dr * 32;
        ub = (float)r;
      }
    }

    return ub;
  }

