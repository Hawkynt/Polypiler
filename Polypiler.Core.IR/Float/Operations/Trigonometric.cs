  /// <summary>
  /// The high 128 bits of the product of two 128-bit fractions, each given as (high, low) words:
  /// the product of the high words plus the high halves of the two cross products, the product of
  /// the low words left out. Writes the high word to <c>product[0]</c> and the low one to <c>product[1]</c>.
  /// </summary>
  private static void TrigMulHigh128(ulong ah, ulong al, ulong bh, ulong bl, ulong[] product) {
    var high = MultiplyHigh(ah, bh);
    var low = unchecked(ah * bh);
    var cross = MultiplyHigh(ah, bl);
    low = unchecked(low + cross);
    high += TrigCarry(low, cross);
    cross = MultiplyHigh(al, bh);
    low = unchecked(low + cross);
    high += TrigCarry(low, cross);
    product[0] = high;
    product[1] = low;
  }

  /// <summary>The carry out of a 64-bit addition: 1 when the wrapped <paramref name="sum"/> is below <paramref name="addend"/>.</summary>
  private static ulong TrigCarry(ulong sum, ulong addend) => sum < addend ? 1UL : 0UL;

  /// <summary>The borrow of a 64-bit subtraction <c>minuend - subtrahend</c>.</summary>
  private static ulong TrigBorrow(ulong minuend, ulong subtrahend) => minuend < subtrahend ? 1UL : 0UL;

  /// <summary>
  /// Whether the 128-bit number (<paramref name="ah"/>, <paramref name="al"/>) is below
  /// (<paramref name="bh"/>, <paramref name="bl"/>): whether their difference borrows out of the high word.
  /// </summary>
  private static bool TrigLess(ulong ah, ulong al, ulong bh, ulong bl)
    => TrigBorrow(ah, bh) + TrigBorrow(unchecked(ah - bh), TrigBorrow(al, bl)) != 0;

  /// <summary>
  /// <c>(-1)^sign * r / 2^128</c> rounded to a double, for a non-zero <c>r</c> whose high word is not
  /// zero: the upper 53 bits of <c>r</c> plus a quarter or three quarters of their last unit, as the
  /// bit after them says, so that the one rounding of the sum rounds <c>r</c> correctly.
  /// </summary>
  private static double TrigToDouble(ulong high, ulong low, int sign) {
    var shift = System.Numerics.BitOperations.LeadingZeroCount(high);
    // r shifted so that its leading bit is bit 127: the upper 53 bits and the round bit are then fixed.
    var top = high << shift | low >> 1 >> (63 - shift);
    var upper = top >> 11;
    var round = (int)(top >> 10 & 1);
    var scale = BitConverter.Int64BitsToDouble(BitConverter.DoubleToInt64Bits(sign == 0 ? 1.1102230246251565E-16 : -1.1102230246251565E-16) - ((long)shift << 52));
    var a = upper * scale;
    var b = (round == 0 ? 0.375 : 0.75) * scale;
    return a + b;
  }

  /// <summary>The low word of the double-double product <c>(xh + xl) * (ch + cl)</c> whose high word is <paramref name="high"/> = <c>xh * ch</c>.</summary>
  private static double TrigMulLow(double xh, double xl, double ch, double cl, double high)
    => (xh * cl + xl * ch) + Math.FusedMultiplyAdd(xh, ch, -high);

  /// <summary>The error of the sum <paramref name="sum"/> = <c>x + y</c>, for <c>|x| &gt;= |y|</c> or <c>x</c> zero.</summary>
  private static double TrigTwoSumLow(double x, double y, double sum) => y - (sum - x);

  /// <summary>
  /// The reduction of a positive <c>x &gt;= 2^31</c> for the fast path: <c>x/(2*pi) mod 1</c> is
  /// <c>j/2^15 + r + s</c> with <c>0 &lt;= r &lt; 2^-15</c> and <c>0 &lt;= s &lt; 2^-67.988</c>. Returns
  /// <c>j</c> and writes <c>r</c> to <c>reduced[0]</c>.
  /// </summary>
  private static int TrigReduceLarge(double x, double[] reduced) {
    var bits = BitConverter.DoubleToInt64Bits(x);
    var e = (int)(bits >> 52 & 0x7ff);
    var m = 1UL << 52 | (ulong)bits & 0xfffffffffffffUL;
    // x = m * 2^(e-1075); the words from i on, shifted by f bits, hold 64 fractional bits of m * them.
    var i = (e - 1011) / 64;
    var f = (e - 1011) & 0x3f;
    ulong v0;
    ulong v1;
    if (f == 0) {
      v0 = _trigInverseTwoPi[i];
      v1 = _trigInverseTwoPi[i + 1];
    } else {
      v0 = _trigInverseTwoPi[i] << f | _trigInverseTwoPi[i + 1] >> (64 - f);
      v1 = _trigInverseTwoPi[i + 1] << f | _trigInverseTwoPi[i + 2] >> (64 - f);
    }

    // u = m * (v0, v1) modulo 2^128.
    var low = unchecked(m * v1);
    var high = unchecked(MultiplyHigh(m, v1) + m * v0);
    // Round r to nearest: add 2^112 + 2^59 + 2^52.
    var rounded = unchecked(low + 0x810000000000000UL);
    high = unchecked(high + (1UL << 48) + TrigCarry(rounded, low));
    // The 53 bits of u after its first 15.
    var r = (double)((high << 4 | rounded >> 60) & 0x1fffffffffffffUL);
    reduced[0] = r * 3.3881317890172014E-21 - 1.52587890625E-05;
    return (int)(high >> 49);
  }

  /// <summary>
  /// The reduction of <c>|x| &gt;= 2^-27</c> for the accurate path: <c>x/(2*pi) mod 1</c> is
  /// <c>k/2^13 + r/2^128 + eps</c> with <c>|r/2^128| &lt;= 2^-14</c> and <c>0 &lt;= eps &lt; 2^-127.999</c>.
  /// Returns <c>k</c> and writes <c>|r|</c> as (high, low) words to <c>reduced[0]</c> and
  /// <c>reduced[1]</c>, and 1 to <c>reduced[2]</c> when <c>r</c> is negative, otherwise 0.
  /// </summary>
  private static int TrigReduceAccurate(double x, ulong[] reduced) {
    var bits = BitConverter.DoubleToInt64Bits(x);
    var e = (int)(bits >> 52 & 0x7ff);
    var m = 1UL << 52 | (ulong)bits & 0xfffffffffffffUL;
    var i = -1 + (e - 947) / 64;
    var f = (e - 1011) & 0x3f;
    var v0 = i >= 0 ? _trigInverseTwoPi[i] : 0UL;
    var v1 = _trigInverseTwoPi[i + 1];
    var v2 = _trigInverseTwoPi[i + 2];
    if (f != 0) {
      v0 = v0 << f | v1 >> (64 - f);
      v1 = v1 << f | v2 >> (64 - f);
      v2 = v2 << f | _trigInverseTwoPi[i + 3] >> (64 - f);
    }

    // m * v0 contributes from 2^-1 to 2^-64, m * v1 from 2^-12 to 2^-128, m * v2 from 2^-76 to
    // 2^-192, of which the part above 2^-128 is added; what is left out is below 2^-128 + 2^-139.
    var low = unchecked(m * v1);
    var high = unchecked(MultiplyHigh(m, v1) + m * v0);
    var tail = MultiplyHigh(m, v2);
    low = unchecked(low + tail);
    high = unchecked(high + TrigCarry(low, tail));
    var k = (int)(high >> 51);
    high &= 0x7ffffffffffffUL;
    // Round k to nearest, so that |r/2^128| < 2^-14.
    var negative = high >> 50;
    if (negative != 0) {
      // Add 1 to k and subtract 2^-13 from r: r becomes 2^115 - r.
      k = (k + 1) & 0x1fff;
      var borrow = TrigBorrow(0UL, low);
      low = unchecked(0UL - low);
      high = (1UL << 51) - high - borrow;
    }

    reduced[0] = high;
    reduced[1] = low;
    reduced[2] = negative;
    return k;
  }

  /// <summary>
  /// <c>sin(2*pi*r)</c> times <c>2^128</c> for <c>0 &lt;= r &lt; 2^-14</c>, in fixed point, from
  /// <c>u = 8*r</c>, <c>u2 = u^2</c> and <c>u4 = u^4</c> (each times <c>2^128</c>, as (high, low) words)
  /// by Estrin's scheme; writes the (high, low) words to <c>result</c>.
  /// </summary>
  private static void TrigSinPolynomial(ulong uh, ulong ul, ulong u2h, ulong u2l, ulong u4h, ulong u4l, ulong[] result) {
    // The terms of degree 5 and 7: (c5 - c7 * u2) * u4.
    var productLow = unchecked(_trigSinPolynomial[7] * u2h);
    var productHigh = MultiplyHigh(_trigSinPolynomial[7], u2h);
    var upperLow = unchecked(_trigSinPolynomial[5] - productLow);
    var upperHigh = unchecked(_trigSinPolynomial[4] - productHigh - TrigBorrow(_trigSinPolynomial[5], productLow));
    TrigMulHigh128(upperHigh, upperLow, u4h, u4l, result);
    upperHigh = result[0];
    upperLow = result[1];
    // The terms of degree 1 and 3: c1 - c3 * u2.
    TrigMulHigh128(_trigSinPolynomial[2], _trigSinPolynomial[3], u2h, u2l, result);
    var lowerLow = unchecked(_trigSinPolynomial[1] - result[1]);
    var lowerHigh = unchecked(_trigSinPolynomial[0] - result[0] - TrigBorrow(_trigSinPolynomial[1], result[1]));
    lowerLow = unchecked(lowerLow + upperLow);
    lowerHigh = unchecked(lowerHigh + upperHigh + TrigCarry(lowerLow, upperLow));
    TrigMulHigh128(lowerHigh, lowerLow, uh, ul, result);
  }

  /// <summary>
  /// <c>cos(2*pi*r)</c> times <c>2^128</c> for <c>0 &lt;= r &lt; 2^-14</c>, in fixed point, from
  /// <c>u2</c> and <c>u4</c> as <see cref="TrigSinPolynomial"/> takes them; writes the (high, low)
  /// words to <c>result</c>.
  /// </summary>
  private static void TrigCosPolynomial(ulong u2h, ulong u2l, ulong u4h, ulong u4l, ulong[] result) {
    // The terms of degree 4 to 8: c4 - (c6 - c8 * u2) * u2.
    var productLow = unchecked(u2h * _trigCosPolynomial[9]);
    var productHigh = MultiplyHigh(u2h, _trigCosPolynomial[9]);
    var upperLow = unchecked(_trigCosPolynomial[7] - productLow);
    var upperHigh = unchecked(_trigCosPolynomial[6] - productHigh - TrigBorrow(_trigCosPolynomial[7], productLow));
    TrigMulHigh128(upperHigh, upperLow, u2h, u2l, result);
    upperLow = unchecked(_trigCosPolynomial[5] - result[1]);
    upperHigh = unchecked(_trigCosPolynomial[4] - result[0] - TrigBorrow(_trigCosPolynomial[5], result[1]));
    // The terms of degree 0 and 2: c0 - c2 * u2.
    TrigMulHigh128(_trigCosPolynomial[2], _trigCosPolynomial[3], u2h, u2l, result);
    var lowerLow = unchecked(_trigCosPolynomial[1] - result[1]);
    var lowerHigh = unchecked(_trigCosPolynomial[0] - result[0] - TrigBorrow(_trigCosPolynomial[1], result[1]));
    TrigMulHigh128(upperHigh, upperLow, u4h, u4l, result);
    var sumLow = unchecked(lowerLow + result[1]);
    result[0] = unchecked(lowerHigh + result[0] + TrigCarry(sumLow, result[1]));
    result[1] = sumLow;
  }

  /// <summary>
  /// The reduction of a binary32 argument of a few multiples of <c>pi</c> (below <c>0x1.2d97c8p+3</c>
  /// for the sine, <c>0x1.a41896p+3</c> for the cosine): <c>x*16/pi</c> minus its nearest integer,
  /// which it writes to <c>quadrant[0]</c>.
  /// </summary>
  private static double TrigFReduceNear(double x, int[] quadrant) {
    var idh = 5.092958178940651 * x;
    var id = Math.Round(idh);
    quadrant[0] = (int)id;
    return idh - id;
  }

  /// <summary>
  /// The reduction of a binary32 argument below <c>2^26</c>: <c>x*16/pi</c> minus its nearest integer,
  /// with <c>16/pi</c> split into two doubles; the integer goes to <c>quadrant[0]</c>.
  /// </summary>
  private static double TrigFReduce(double x, int[] quadrant) {
    var idl = -3.1558305786379073E-09 * x;
    var idh = 5.092958182096481 * x;
    var id = Math.Round(idh);
    quadrant[0] = (int)id;
    return (idh - id) + idl;
  }

  /// <summary>
  /// The reduction of a finite binary32 argument above <c>2^26</c>, given by its bits: the product of
  /// its significand with 256 bits of <c>16/pi</c>, of which the integer part modulo <c>2^32</c>, rounded
  /// to nearest, goes to <c>quadrant[0]</c> and the fraction, in <c>[-1/2, 1/2]</c>, is returned; both
  /// carry the sign of the argument.
  /// </summary>
  private static double TrigFReduceLarge(uint u, int[] quadrant) {
    var e = (int)(u >> 23 & 0xff);
    var m = (ulong)(u & 0x7fffffu | 1u << 23);
    var p0h = MultiplyHigh(m, _trigFSixteenOverPi[0]);
    var p1l = unchecked(m * _trigFSixteenOverPi[1] + p0h);
    var p1h = MultiplyHigh(m, _trigFSixteenOverPi[1]) + TrigCarry(p1l, p0h);
    var p2l = unchecked(m * _trigFSixteenOverPi[2] + p1h);
    var p2h = MultiplyHigh(m, _trigFSixteenOverPi[2]) + TrigCarry(p2l, p1h);
    var p3l = unchecked(m * _trigFSixteenOverPi[3] + p2h);
    var p3h = MultiplyHigh(m, _trigFSixteenOverPi[3]) + TrigCarry(p3l, p2h);
    // 155 <= e <= 254 gives 5 <= s <= 104: the integer part ends s bits into the 256-bit product.
    var s = e - 124 - 23;
    int i;
    long a;
    if (s < 64) {
      i = unchecked((int)(p3h << s | p3l >> (64 - s)));
      a = unchecked((long)(p3l << s | p2l >> (64 - s)));
    } else if (s == 64) {
      i = unchecked((int)p3l);
      a = unchecked((long)p2l);
    } else {
      i = unchecked((int)(p3l << (s - 64) | p2l >> (128 - s)));
      a = unchecked((long)(p2l << (s - 64) | p1l >> (128 - s)));
    }

    var sign = unchecked((int)u) >> 31;
    // A fraction of a half or more rounds the integer up; as a signed number it is then negative.
    var up = a >> 63;
    i = unchecked(i - (int)up);
    var z = (a ^ sign) * 5.421010862427522E-20;
    i = unchecked((i ^ sign) - sign);
    quadrant[0] = i;
    return z;
  }

