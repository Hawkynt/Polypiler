  /// <summary>
  /// The binary logarithm, correctly rounded: two tables of 33 reciprocals and a polynomial of degree 5
  /// give the result to about 2^-72; when that cannot decide the rounding, four tables and a
  /// double-double polynomial refine it. A power of two gives its exponent exactly.
  /// </summary>
  /// <param name="x">The number.</param>
  /// <returns><c>log2 x</c>; negative infinity for a zero, NaN for a negative number or a NaN.</returns>
  public static double Log2(double x) {
    var t = (ulong)BitConverter.DoubleToInt64Bits(x);
    var ex = (int)(t >> 52);
    var e = ex - 0x3ff;
    if (ex == 0) {
      if (t == 0)
        return double.NegativeInfinity;

      // A subnormal number, normalized.
      var k = System.Numerics.BitOperations.LeadingZeroCount(t);
      e -= k - 12;
      t <<= k - 11;
    }

    if (ex >= 0x7ff) {
      if (t << 1 == 0)
        return double.NegativeInfinity;

      if (t << 1 > 0x7ffUL << 53)
        return x + x;

      return t >> 63 != 0 ? double.NaN : x;
    }

    t &= ~0UL >> 12;
    if (t == 0)
      return e;

    // The index of two reciprocals whose product is close to 1 / x, from a piecewise linear guess.
    double ed = e;
    var i = (int)(t >> (52 - 5));
    var d = (long)(t & (~0UL >> 17));
    var j = unchecked(t + ((ulong)_log2Index[2 * i] << 33) + (ulong)((long)_log2Index[2 * i + 1] * (d >> 16))) >> (52 - 10);
    t |= 0x3ffUL << 52;
    var i1 = (int)(j >> 5);
    var i2 = (int)(j & 0x1f);
    var tf = BitConverter.Int64BitsToDouble((long)t);
    const double Log2EHigh = 1.4426956176757812; // 0x1.71548p+0
    const double Log2ELow = -3.9979799673326663E-07; // -0x1.ad47a2f472159p-22
    var r = _log2Reciprocal1[i1] * _log2Reciprocal2[i2];
    var o = r * tf;
    var dxl = Math.FusedMultiplyAdd(r, tf, -o);
    var dxh = o - Log2EHigh;
    var dx = dxh + dxl;
    var dx2 = dx * dx;
    var f = dx2 * ((_log2Polynomial[0] + dx * _log2Polynomial[1]) + dx2 * (_log2Polynomial[2] + dx * _log2Polynomial[3]));
    var lt = (_log2ReciprocalLog1[2 * i1 + 1] + _log2ReciprocalLog2[2 * i2 + 1]) + ed;
    var lh = lt + dxh;
    var ll = (lt - lh) + dxh;
    ll += ((_log2ReciprocalLog1[2 * i1] + _log2ReciprocalLog2[2 * i2]) + dxl) + dxh * Log2ELow;
    ll += f;
    const double Epsilon = 2.64E-22;
    var lb = lh + (ll - Epsilon);
    var ub = lh + (ll + Epsilon);
    return lb == ub ? lb : Log2Refine(x, ub);
  }

  /// <summary>
  /// The binary logarithm of a <c>float</c>, correctly rounded: a table of 65 reciprocals and a
  /// polynomial of degree 3, refined with one of degree 6 when the first cannot decide the rounding.
  /// A power of two gives its exponent exactly.
  /// </summary>
  /// <param name="x">The number.</param>
  /// <returns><c>log2 x</c>; negative infinity for a zero, NaN for a negative number or a NaN.</returns>
  public static float Log2F(float x) {
    var ux = (uint)BitConverter.SingleToInt32Bits(x);
    if (ux >= 0x7f800000u)
      return LogSpecialF(x);

    if (ux < 1u << 23) {
      if (ux == 0u)
        return LogSpecialF(x);

      // A subnormal number, normalized.
      var n = System.Numerics.BitOperations.LeadingZeroCount(ux) - 8;
      ux <<= n;
      ux -= (uint)(n << 23);
    }

    var e = ((int)ux >> 23) - 0x7f;
    var m = ux & (~0u >> 9);
    if (m == 0)
      return e;

    var j = (int)((m + (1u << (23 - 7))) >> (23 - 6));
    var xd = BitConverter.Int64BitsToDouble((long)((ulong)m << (52 - 23) | 0x3ffUL << 52));
    var z = xd * _logReciprocalF[j] - 1.0;
    var z2 = z * z;
    var el = e - _log2ReciprocalLogF[j];
    var f = (el + z * _log2FastF[0]) + z2 * (_log2FastF[1] + z * _log2FastF[2]);
    var lb = (float)f;
    var ub = (float)(f + 3.256559466535691E-10); // 0x1.661p-32
    if (lb == ub)
      return lb;

    var c0 = _log2PolynomialF[0] + z * _log2PolynomialF[1];
    var c2 = _log2PolynomialF[2] + z * _log2PolynomialF[3];
    var c4 = _log2PolynomialF[4] + z * _log2PolynomialF[5];
    c0 += z2 * (c2 + z2 * c4);
    return (float)(el + z * c0);
  }

  /// <summary>
  /// The binary logarithm refined to about 2^-100: x times four reciprocals from tables of 17 and
  /// 16 entries is close enough to 1 for a double-double polynomial of degree 6. <paramref name="a"/>
  /// is the first approximation, which selects the reciprocals.
  /// </summary>
  private static double Log2Refine(double x, double a) {
    var t = (ulong)BitConverter.DoubleToInt64Bits(x);
    var ex = (int)(t >> 52);
    var e = ex - 0x3ff;
    if (ex == 0) {
      var k = System.Numerics.BitOperations.LeadingZeroCount(t);
      e -= k - 12;
      t <<= k - 11;
    }

    t &= ~0UL >> 12;
    t |= 0x3ffUL << 52;
    var tf = BitConverter.Int64BitsToDouble((long)t);
    double ed = e;
    var v = BitConverter.DoubleToInt64Bits(a - ed + 1.0000076293945312); // 0x1.00008p+0
    var i = (int)((ulong)(v - (0x3ffL << 52)) >> (52 - 16));
    var i1 = i >> 12;
    var i2 = (i >> 8) & 0xf;
    var i3 = (i >> 4) & 0xf;
    var i4 = i & 0xf;

    // The logarithms of the four reciprocals as a triple-double, LL[n][i][part] at (17 n + i) * 3 + part.
    var n1 = i1 * 3;
    var n2 = (17 + i2) * 3;
    var n3 = (34 + i3) * 3;
    var n4 = (51 + i4) * 3;
    var l0 = _log2RefineLog[n1] + _log2RefineLog[n2] + (_log2RefineLog[n3] + _log2RefineLog[n4]) + ed;
    var l1 = _log2RefineLog[n1 + 1] + _log2RefineLog[n2 + 1] + (_log2RefineLog[n3 + 1] + _log2RefineLog[n4 + 1]);
    var l2 = _log2RefineLog[n1 + 2] + _log2RefineLog[n2 + 2] + (_log2RefineLog[n3 + 2] + _log2RefineLog[n4 + 2]);

    // x times the reciprocals, minus 1, in double-double.
    var t12 = _log2Refine1[i1] * _log2Refine2[i2];
    var t34 = _log2Refine3[i3] * _log2Refine4[i4];
    var th = t12 * t34;
    var tl = Math.FusedMultiplyAdd(t12, t34, -th);
    var dh = th * tf;
    var dl = Math.FusedMultiplyAdd(th, tf, -dh);
    var sh = tl * tf;
    var sl = Math.FusedMultiplyAdd(tl, tf, -sh);
    var low = new double[1];
    var xh = LogFastTwoSum(dh - 1, dl, low);
    var xl = low[0];
    xh = Log2AddDD(xh, xl, sh, sl, low);
    xl = low[0];

    // The polynomial: the three low coefficients in double, the three high ones in double-double.
    sl = xh * (_log2RefineTail[0] + xh * (_log2RefineTail[1] + xh * _log2RefineTail[2]));
    var ch = _log2RefinePolynomial[4] + sl;
    var cl = ((_log2RefinePolynomial[4] - ch) + sl) + _log2RefinePolynomial[5];
    for (var degree = 1; degree >= 0; degree--) {
      ch = Log2MultiplyDD(xh, xl, ch, cl, low);
      cl = low[0];
      var sumHigh = ch + _log2RefinePolynomial[2 * degree];
      var sumLow = (_log2RefinePolynomial[2 * degree] - sumHigh) + ch;
      ch = sumHigh;
      cl += sumLow + _log2RefinePolynomial[2 * degree + 1];
    }

    sh = Log2MultiplyDD(xh, xl, ch, cl, low);
    sl = low[0];
    sh = Log2AddDD(sh, sl, l1, l2, low);
    sl = low[0];
    var v0 = LogFastTwoSum(l0, sh, low);
    var v2 = low[0];
    var v1 = LogFastTwoSum(v2, sl, low);
    v2 = low[0];

    // A middle part that is a power of two may hide a halfway case: move it one ulp toward the low part.
    var w = BitConverter.DoubleToInt64Bits(v1);
    if ((w & (long)(~0UL >> 12)) == 0) {
      var d = 2 * ((w ^ BitConverter.DoubleToInt64Bits(v2)) >> 63) + 1;
      v1 = BitConverter.Int64BitsToDouble(w + d);
    }

    return v1 + v0;
  }

  /// <summary>The double-double sum of two double-doubles; the high part is returned, the low one written to <c>low[0]</c>.</summary>
  private static double Log2AddDD(double xh, double xl, double ch, double cl, double[] low) {
    var s = xh + ch;
    var d = s - xh;
    low[0] = ((ch - d) + (xh + (d - s))) + (xl + cl);
    return s;
  }

  /// <summary>The double-double product of two double-doubles; the high part is returned, the low one written to <c>low[0]</c>.</summary>
  private static double Log2MultiplyDD(double xh, double xl, double ch, double cl, double[] low) {
    var ahlh = ch * xl;
    var alhh = cl * xh;
    var ahhh = ch * xh;
    var ahhl = Math.FusedMultiplyAdd(ch, xh, -ahhh);
    ahhl += alhh + ahlh;
    return LogFastTwoSum(ahhh, ahhl, low);
  }

  /// <summary>
  /// The sum of two numbers, |x| &gt;= |y|, as a double-double: the rounded sum is returned and its
  /// error written to <c>low[0]</c>.
  /// </summary>
  private static double LogFastTwoSum(double x, double y, double[] low) {
    var s = x + y;
    var z = s - x;
    low[0] = y - z;
    return s;
  }

