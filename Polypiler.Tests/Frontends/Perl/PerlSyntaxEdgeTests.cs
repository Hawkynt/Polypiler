  [TestCase("use Foo map { $_ } 1; frob 1;")]
  [TestCase("use Filter::cpp;")]
  [TestCase("use Syntax::Feature::Junction;")]
  [TestCase("my $x = \"@{[ <<E ]}\";\nE\n")]
  [TestCase("our sub f { }")]
  [TestCase("use feature 'state'; state sub f { }")]
  [TestCase("use feature 'class'; field $x;")]
  [TestCase("use feature 'switch'; when (1) { }")]
  [TestCase("use feature 'switch'; default { }")]
  [TestCase("CORE::when (1) { }")]
  [TestCase("#!/usr/bin/perl -p\n1;")]
  [TestCase("my $x = /(??{ 1 })/;")]
  [TestCase("my $x = /(*{ 1 })/;")]
  public void UnsupportedSnippets(string source) {
    var result = Parse(source);
    Assert.That(result.Verdict, Is.EqualTo(PerlVerdict.Unsupported), string.Join("\n", result.Diagnostics));
  }

