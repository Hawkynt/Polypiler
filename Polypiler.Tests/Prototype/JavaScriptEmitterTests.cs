  private static string Emit(string methods)
    => JavaScriptEmitter.Emit(PrototypeFixture.Import("Snippet.cs", PrototypeFixture.Wrap(methods))).Single().Content;

  /// <summary>The body of the function <c>F</c>, one line per statement, without indentation.</summary>
  private static string[] Body(string methods) {
    var lines = Emit(methods).Split('\n');
    var start = System.Array.FindIndex(lines, line => line.Contains("function F("));
    return lines.Skip(start + 1).TakeWhile(line => line != "}").Select(line => line.Trim()).ToArray();
  }

  [TestCaseSource(typeof(PrototypeFixture), nameof(PrototypeFixture.Names))]
  public void Fixture_BecomesOneModuleNamedAfterItsClass(string fixture) {
    var files = JavaScriptEmitter.Emit(PrototypeFixture.Import(PrototypeFixture.ClassOf(fixture) + ".cs", PrototypeFixture.SourceOf(fixture)));
    Assert.That(files.Select(file => file.Path), Is.EqualTo(new[] { PrototypeFixture.ClassOf(fixture) + ".mjs" }));
    Assert.That(files[0].Content, Does.StartWith($"// {PrototypeFixture.ClassOf(fixture)}: generated by polypiler.").And.EndWith("}\n"));
    Assert.That(files[0].Content, Does.Not.Contain("\r").And.Not.Contain("\t"));
  }

  /// <summary>The whole module for one small function: helpers first, two-space indent, original identifiers.</summary>
  [Test]
  public void Module_IsReadable() {
    var text = Emit("public static uint Sum(byte[] data) { uint sum = 0; for (int i = 0; i < data.Length; ++i) sum += data[i]; return sum; }");
    Assert.That(text, Is.EqualTo(string.Join('\n',
      "// Snippet: generated by polypiler. Change the source, not this file.",
      "",
      "function $get(array, index) {",
      "  if (index < 0 || index >= array.length) throw new RangeError(\"index out of range\");",
      "  return array[index];",
      "}",
      "",
      "// Sum(data: Uint8Array): number",
      "export function Sum(data) {",
      "  let sum = 0;",
      "  {",
      "    let i = 0;",
      "    while (i < data.length) {",
      "      sum = (sum + $get(data, i)) >>> 0;",
      "      i = (i + 1) | 0;",
      "    }",
      "  }",
      "  return sum;",
      "}",
      "")));
  }

