using System.Linq;
using NUnit.Framework;
using Polypiler.Core;
using Polypiler.Core.Backends.JavaScript;
using Polypiler.Core.IR;
using Polypiler.Prototype.Testing;

namespace Polypiler.Tests.Prototype;

/// <summary>
/// The text the emitter writes. Whether that text computes the right thing is not decided here but
/// by running it in node, in the acceptance tests.
/// </summary>
[TestFixture]
public sealed class JavaScriptEmitterTests {

  private static string Emit(string methods)
    => JavaScriptEmitter.Emit(PrototypeFixture.Import("Snippet.cs", PrototypeFixture.Wrap(methods))).Single().Content;

  /// <summary>The body of the function <c>F</c>, one line per statement, without indentation.</summary>
  private static string[] Body(string methods) {
    var lines = Emit(methods).Split('\n');
    var start = System.Array.FindIndex(lines, line => line.Contains("function F("));
    return lines.Skip(start + 1).TakeWhile(line => line != "}").Select(line => line.Trim()).ToArray();
  }

  [TestCaseSource(typeof(PrototypeFixture), nameof(PrototypeFixture.Names))]
  public void Fixture_BecomesOneModuleNamedAfterItsClass(string fixture) {
    var files = JavaScriptEmitter.Emit(PrototypeFixture.Import(fixture + ".cs", PrototypeFixture.SourceOf(fixture)));
    Assert.That(files.Select(file => file.Path), Is.EqualTo(new[] { fixture + ".mjs" }));
    Assert.That(files[0].Content, Does.StartWith($"// {fixture}: generated by polypiler.").And.EndWith("}\n"));
    Assert.That(files[0].Content, Does.Not.Contain("\r").And.Not.Contain("\t"));
  }

  /// <summary>The whole module for one small function: helpers first, two-space indent, original identifiers.</summary>
  [Test]
  public void Module_IsReadable() {
    var text = Emit("public static uint Sum(byte[] data) { uint sum = 0; for (int i = 0; i < data.Length; ++i) sum += data[i]; return sum; }");
    Assert.That(text, Is.EqualTo(string.Join('\n',
      "// Snippet: generated by polypiler. Change the source, not this file.",
      "",
      "function $get(array, index) {",
      "  if (index < 0 || index >= array.length) throw new RangeError(\"index out of range\");",
      "  return array[index];",
      "}",
      "",
      "export function Sum(data) {",
      "  let sum = 0;",
      "  {",
      "    let i = 0;",
      "    while (i < data.length) {",
      "      sum = (sum + $get(data, i)) >>> 0;",
      "      i = (i + 1) | 0;",
      "    }",
      "  }",
      "  return sum;",
      "}",
      "")));
  }

  /// <summary>Each operator in the form that keeps a JavaScript number inside its 32 bits.</summary>
  [TestCase("int", "a + b", "(a + b) | 0")]
  [TestCase("int", "a - b", "(a - b) | 0")]
  [TestCase("int", "a * b", "Math.imul(a, b)")]
  [TestCase("int", "a / b", "$div(a, b)")]
  [TestCase("int", "a % b", "$rem(a, b)")]
  [TestCase("int", "a & b", "a & b")]
  [TestCase("int", "a | b", "a | b")]
  [TestCase("int", "a ^ b", "a ^ b")]
  [TestCase("int", "a << b", "a << b")]
  [TestCase("int", "a >> b", "a >> b")]
  [TestCase("int", "a >>> b", "(a >>> b) | 0")]
  [TestCase("int", "-a", "-a | 0")]
  [TestCase("int", "~a", "~a")]
  [TestCase("int", "a - -5", "(a - (-5)) | 0")]
  [TestCase("int", "-(a + b)", "-((a + b) | 0) | 0")]
  [TestCase("int", "a * (b + 1)", "Math.imul(a, (b + 1) | 0)")]
  [TestCase("uint", "a + b", "(a + b) >>> 0")]
  [TestCase("uint", "a - b", "(a - b) >>> 0")]
  [TestCase("uint", "a * b", "Math.imul(a, b) >>> 0")]
  [TestCase("uint", "a / b", "$udiv(a, b)")]
  [TestCase("uint", "a % b", "$urem(a, b)")]
  [TestCase("uint", "a & b", "(a & b) >>> 0")]
  [TestCase("uint", "a | b", "(a | b) >>> 0")]
  [TestCase("uint", "a ^ b", "(a ^ b) >>> 0")]
  [TestCase("uint", "a << 3", "(a << 3) >>> 0")]
  [TestCase("uint", "a >> 3", "a >>> 3")]
  [TestCase("uint", "a >>> 3", "a >>> 3")]
  [TestCase("uint", "~a", "~a >>> 0")]
  [TestCase("uint", "(a * b) + a", "((Math.imul(a, b) >>> 0) + a) >>> 0")]
  public void Arithmetic_IsWrittenToWrap(string type, string expression, string expected)
    => Assert.That(Body($"public static {type} F({type} a, {type} b) => {expression};"), Is.EqualTo(new[] { $"return {expected};" }));

  [TestCase("a == b", "a === b")]
  [TestCase("a != b", "a !== b")]
  [TestCase("a < b", "a < b")]
  [TestCase("a <= b", "a <= b")]
  [TestCase("a > b", "a > b")]
  [TestCase("a >= b", "a >= b")]
  [TestCase("a < b && b < 3", "(a < b) && (b < 3)")]
  [TestCase("a < b || !(b < 3)", "(a < b) || (!(b < 3))")]
  [TestCase("true", "true")]
  [TestCase("false", "false")]
  public void Comparison_IsWritten(string expression, string expected)
    => Assert.That(Body($"public static bool F(int a, int b) => {expression};"), Is.EqualTo(new[] { $"return {expected};" }));

  /// <summary>Test design 4: each cast, and the promotion of a byte, which needs no code.</summary>
  [TestCase("uint", "int", "(uint)a", "a >>> 0")]
  [TestCase("byte", "int", "(byte)a", "a & 0xFF")]
  [TestCase("int", "uint", "(int)a", "a | 0")]
  [TestCase("byte", "uint", "(byte)a", "a & 0xFF")]
  [TestCase("int", "byte", "a", "a")]
  [TestCase("uint", "byte", "a", "a")]
  [TestCase("byte", "byte", "(byte)(a + 1)", "((a + 1) | 0) & 0xFF")]
  [TestCase("int", "bool", "a ? 1 : -1", "a ? 1 : (-1)")]
  public void Conversion_IsWritten(string to, string from, string expression, string expected)
    => Assert.That(Body($"public static {to} F({from} a) => {expression};"), Is.EqualTo(new[] { $"return {expected};" }));

  /// <summary>Test design 5: each array type, read, write, length and creation.</summary>
  [TestCase("int", "Int32Array")]
  [TestCase("uint", "Uint32Array")]
  [TestCase("byte", "Uint8Array")]
  public void Array_UsesTheTypedArrayOfItsElement(string element, string storage) {
    var body = Body($"public static {element}[] F({element}[] a, int n) {{ {element}[] b = new {element}[n + a.Length]; b[0] = a[1]; return b; }}");
    Assert.That(body, Is.EqualTo(new[] {
      $"let b = new {storage}($len((n + a.length) | 0));",
      "$set(b, 0, $get(a, 1));",
      "return b;"
    }));
  }

  [Test]
  public void Statements_AreWritten() {
    var body = Body(
      "public static void G() { } private static int H(int a) => a; "
      + "public static int F(int a, int[] d) { int x; if (a < 0) { x = 1; } else if (a == 0) x = 2; else { x = 3; x = 4; } "
      + "if (a > 9) return 0; else x = 5; while (x < a) x++; { int y = H(x); G(); d[0] = y; } return x; }");
    Assert.That(body, Is.EqualTo(new[] {
      "let x;",
      "if (a < 0) {",
      "x = 1;",
      "} else if (a === 0) {",
      "x = 2;",
      "} else {",
      "x = 3;",
      "x = 4;",
      "}",
      "if (a > 9) {",
      "return 0;",
      "} else {",
      "x = 5;",
      "}",
      "while (x < a) {",
      "x = (x + 1) | 0;",
      "}",
      "{",
      "let y = H(x);",
      "G();",
      "$set(d, 0, y);",
      "}",
      "return x;"
    }));
  }

  [Test]
  public void OnlyPublicFunctions_AreExported() {
    var text = Emit("public static void A() { return; } private static void B() { } internal static void C() { }");
    Assert.That(text, Does.Contain("\nexport function A() {\n  return;\n}\n").And.Contain("\nfunction B() {\n}\n").And.Contain("\nfunction C() {\n}\n"));
    Assert.That(text, Does.Not.Contain("function $"));
  }

  /// <summary>Only the helpers a module uses are in it, always in the same order.</summary>
  [Test]
  public void Helpers_AreListedOnceAndOnlyWhenUsed() {
    var text = Emit("public static int F(int[] a, uint u) { a[0] = a[1] / a[2] % a[3]; return (int)(u / 2 % 3) + new int[2].Length; }");
    var helpers = text.Split('\n').Where(line => line.StartsWith("function $")).Select(line => line[..line.IndexOf('(')]);
    Assert.That(helpers, Is.EqualTo(new[] { "function $div", "function $rem", "function $udiv", "function $urem", "function $get", "function $set", "function $len" }));
    Assert.That(text, Does.Contain("throw new RangeError(\"divide by zero\")")
      .And.Contain("throw new RangeError(\"index out of range\")")
      .And.Contain("throw new RangeError(\"integer overflow\")"));
  }

  /// <summary>An identifier JavaScript reserves, or one the emitted code needs itself, is renamed visibly.</summary>
  [Test]
  public void ReservedIdentifiers_GetADollarSign() {
    var text = Emit("public static int @function(int @var, int Math) { int @let = @var * Math; return @let; } public static int F(int a) => @function(a, a);");
    Assert.That(text, Does.Contain("export function function$(var$, Math$) {\n  let let$ = Math.imul(var$, Math$);\n  return let$;\n}"));
    Assert.That(text, Does.Contain("return function$(a, a);"));
  }

  [Test]
  public void IllTypedModule_IsNotEmitted() {
    var module = new IrModule("M", [new IrFunction("F", true, IrType.I32, [], [], new IrBlock([new IrReturn(new IrConst(IrType.Bool, 1))]))]);
    Assert.That(() => JavaScriptEmitter.Emit(module),
      Throws.ArgumentException.With.Message.Contains("The module 'M' cannot be emitted: ill-typed IR in 'F'"));
  }

  [Test]
  public void GeneratedFile_CarriesPathAndContent() {
    var file = new GeneratedFile("a.mjs", "text");
    Assert.That((file.Path, file.Content), Is.EqualTo(("a.mjs", "text")));
    Assert.That(file, Is.EqualTo(new GeneratedFile("a.mjs", "text")));
  }

}
