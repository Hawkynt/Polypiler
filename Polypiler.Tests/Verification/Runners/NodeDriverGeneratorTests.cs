using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Text.Json.Nodes;
using NUnit.Framework;
using Polypiler.Core.Verification.Images;
using Polypiler.Core.Verification.Runners;

namespace Polypiler.Tests.Verification.Runners;

/// <summary>
/// The JavaScript driver generator (#234): the constants it puts in front of the shared driver, the
/// entry module and module system of a run, and the description of every image type the driver reads.
/// The acceptance project runs the drivers on the locked node.
/// </summary>
[TestFixture]
public sealed class NodeDriverGeneratorTests {

  private static IReadOnlyDictionary<string, ReadOnlyMemory<byte>> Files(params (string Name, string Text)[] files)
    => files.ToDictionary(file => file.Name, file => (ReadOnlyMemory<byte>)Encoding.UTF8.GetBytes(file.Text), StringComparer.Ordinal);

  private static readonly CallSignature _signature = new([
    new CallParameter("a", ImageType.I32, ParameterMode.In), new CallParameter("b", ImageType.Seq(ImageType.U8), ParameterMode.InOut),
    new CallParameter("c", ImageType.U64, ParameterMode.Out)], ImageType.Utf16);

  [Test]
  public void TheDriver_IsTheConstantsOfTheExportInFrontOfTheTemplate() {
    var driver = NodeDriverGenerator.Generate("lib/adler32.mjs", "Lib.adler32", _signature);

    Assert.That(driver, Does.StartWith("// <auto-generated/> The Polypiler driver of Lib.adler32.\n"));
    Assert.That(driver, Does.Contain("const ENTRY = \"./lib/adler32.mjs\";\nconst COMMONJS = false;\nconst EXPORT = \"Lib.adler32\";\n"));
    Assert.That(driver, Does.Contain("const SIGNATURE = {\"p\":[{\"n\":\"a\",\"m\":\"in\",\"t\":{\"k\":\"int\",\"n\":\"i32\",\"w\":4,\"s\":true}},"
      + "{\"n\":\"b\",\"m\":\"inout\",\"t\":{\"k\":\"seq\",\"e\":{\"k\":\"int\",\"n\":\"u8\",\"w\":1,\"s\":false}}},"
      + "{\"n\":\"c\",\"m\":\"out\",\"t\":{\"k\":\"int\",\"n\":\"u64\",\"w\":8,\"s\":false}}],\"r\":{\"k\":\"utf16\"}};"));
    Assert.That(driver, Does.EndWith(NodeDriverGenerator.Template));
    Assert.That(NodeDriverGenerator.Template, Does.Contain("async function main()").And.Not.Contain("\r"));
  }

  [Test]
  public void AVoidSignature_HasANullResult_AndQuotesAreEscaped() {
    var driver = NodeDriverGenerator.Generate("a\"b.cjs", "F", new CallSignature([], null));

    Assert.That(driver, Does.Contain("const ENTRY = \"./a\\u0022b.cjs\";\nconst COMMONJS = true;"));
    Assert.That(driver, Does.Contain("const SIGNATURE = {\"p\":[],\"r\":null};"));
  }

  [TestCase("index.mjs", false)]
  [TestCase("index.cjs", true)]
  [TestCase("index.js", true)]
  public void TheModuleSystem_FollowsTheExtension(string entry, bool commonJs)
    => Assert.That(NodeDriverGenerator.Generate(entry, "F", _signature), Does.Contain($"const COMMONJS = {(commonJs ? "true" : "false")};"));

  [TestCase("{\"type\":\"module\",\"main\":\"main.js\"}", "main.js", false)]
  [TestCase("{\"type\":\"commonjs\",\"main\":\"./main.js\"}", "main.js", true)]
  [TestCase("{\"exports\":\"./main.js\",\"main\":\"other.js\"}", "main.js", true)]
  [TestCase("{\"exports\":{\".\":\"./main.js\"},\"main\":\"other.js\"}", "other.js", true)]
  [TestCase("{\"name\":\"x\",\"type\":7}", "index.js", true)]
  public void APackageJson_NamesTheEntryAndTheModuleSystem(string package, string entry, bool commonJs) {
    var files = Files(("package.json", package), ("main.js", ""), ("other.js", ""), ("index.js", ""));

    Assert.That(NodeDriverGenerator.Entry(files), Is.EqualTo(entry));
    Assert.That(NodeDriverGenerator.Generate(files, "F", _signature), Does.Contain($"const ENTRY = \"./{entry}\";\nconst COMMONJS = {(commonJs ? "true" : "false")};"));
  }

  [Test]
  public void TheIndexModules_AreTriedInOrder_ThenTheOnlyScript() {
    Assert.That(NodeDriverGenerator.Entry(Files(("index.js", ""), ("index.cjs", ""), ("index.mjs", ""))), Is.EqualTo("index.mjs"));
    Assert.That(NodeDriverGenerator.Entry(Files(("index.js", ""), ("index.cjs", ""))), Is.EqualTo("index.cjs"));
    Assert.That(NodeDriverGenerator.Entry(Files(("index.js", ""), ("lib.mjs", ""))), Is.EqualTo("index.js"));
    Assert.That(NodeDriverGenerator.Entry(Files(("lib/only.mjs", ""), ("data.json", "{}"))), Is.EqualTo("lib/only.mjs"));
  }

  [TestCase("{\"main\":\"gone.js\"}", "names the entry 'gone.js', which is not among the files")]
  [TestCase("[1]", "package.json is not a JSON object")]
  [TestCase("{", "package.json is not JSON")]
  public void ABrokenPackageJson_IsRefused(string package, string reason)
    => Assert.That(Assert.Throws<ArgumentException>(() => NodeDriverGenerator.Entry(Files(("package.json", package), ("a.mjs", ""))))!.Message, Does.Contain(reason));

  [TestCase(0)]
  [TestCase(2)]
  public void NoOrSeveralScriptsWithoutAnIndex_AreRefused(int scripts) {
    var files = Files([.. Enumerable.Range(0, scripts).Select(index => ($"m{index}.mjs", "")), ("readme.txt", "")]);

    Assert.That(Assert.Throws<ArgumentException>(() => NodeDriverGenerator.Entry(files))!.Message, Does.Contain($"no entry module among {scripts} JavaScript file(s)"));
  }

  [TestCase("a..b")]
  [TestCase(".a")]
  [TestCase("a.")]
  public void AnExportWithAnEmptySegment_IsRefused(string export)
    => Assert.That(Assert.Throws<ArgumentException>(() => NodeDriverGenerator.Generate("a.mjs", export, _signature))!.Message, Does.Contain("empty segment"));

  [TestCase("a.js", true)]
  [TestCase("a.mjs", true)]
  [TestCase("a.cjs", true)]
  [TestCase("a.json", false)]
  [TestCase("a.ts", false)]
  public void AScript_IsAJsMjsOrCjsFile(string name, bool script) => Assert.That(NodeDriverGenerator.IsScript(name), Is.EqualTo(script));

  [TestCase("i8", "{\"k\":\"int\",\"n\":\"i8\",\"w\":1,\"s\":true}")]
  [TestCase("f32", "{\"k\":\"float\",\"n\":\"f32\",\"w\":4}")]
  [TestCase("bool", "{\"k\":\"bool\"}")]
  [TestCase("char16", "{\"k\":\"char16\"}")]
  [TestCase("bigint", "{\"k\":\"bigint\"}")]
  [TestCase("bytes", "{\"k\":\"bytes\"}")]
  [TestCase("utf8", "{\"k\":\"utf8\"}")]
  [TestCase("utf16", "{\"k\":\"utf16\"}")]
  [TestCase("opt<f64>", "{\"k\":\"opt\",\"e\":{\"k\":\"float\",\"n\":\"f64\",\"w\":8}}")]
  [TestCase("enum<u16>", "{\"k\":\"enum\",\"e\":{\"k\":\"int\",\"n\":\"u16\",\"w\":2,\"s\":false}}")]
  [TestCase("record{hi:bool,lo:utf8}", "{\"k\":\"record\",\"f\":[[\"hi\",{\"k\":\"bool\"}],[\"lo\",{\"k\":\"utf8\"}]]}")]
  [TestCase("tuple<bool,utf8>", "{\"k\":\"tuple\",\"f\":[{\"k\":\"bool\"},{\"k\":\"utf8\"}]}")]
  [TestCase("union<bool|null>", "{\"k\":\"union\",\"f\":[{\"k\":\"bool\"},{\"k\":\"null\"}]}")]
  public void EveryImageType_IsDescribedForTheDriver(string type, string json)
    => Assert.That(NodeDriverGenerator.Describe(ImageType.Parse(type)).ToJsonString(), Is.EqualTo(json));

  [Test]
  public void InvalidArguments_AreRefused() {
    Assert.Throws<ArgumentException>(() => NodeDriverGenerator.Generate(" ", "F", _signature));
    Assert.Throws<ArgumentException>(() => NodeDriverGenerator.Generate("a.mjs", "", _signature));
    Assert.Throws<ArgumentNullException>(() => NodeDriverGenerator.Generate("a.mjs", "F", null!));
    Assert.Throws<ArgumentNullException>(() => NodeDriverGenerator.Entry(null!));
    Assert.Throws<ArgumentNullException>(() => NodeDriverGenerator.IsScript(null!));
    Assert.Throws<ArgumentNullException>(() => NodeDriverGenerator.Describe(null!));
    Assert.That(NodeDriverGenerator.Describe(ImageType.Null), Is.InstanceOf<JsonObject>());
  }

}
