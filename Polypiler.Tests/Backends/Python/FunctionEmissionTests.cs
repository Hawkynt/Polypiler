/// <summary>
/// The module the functions issue (#445) asks for: typed functions, <c>__all__</c> with the public
/// functions in snake_case, private ones behind an underscore, the names Python reserves avoided,
/// constants and globals of the module, arrays as lists, steps, and the header; the names that
/// collide are refused. The O0501 pass removes what nothing names.
/// </summary>
[TestFixture]
public sealed class FunctionEmissionTests {

  private static readonly IrLocal _x = L("x", IrType.I32), _y = L("y", IrType.I32);

  private static IrFunction Private(IrFunction function) => function with { IsPublic = false };

  [Test]
  public void Module_IsTyped_AndListsItsPublicFunctionsInAll() {
    var data = L("data", IrType.Array(IrType.U8));
    var module = new IrModule("Hawkynt.Checksums.Adler32", [
      Function("computeChecksum", IrType.I32, [data], new IrReturn(new IrCall("Helper", IrType.I32, [new IrArrayLength(R(data))]))),
      Private(Function("Helper", IrType.I32, [_x], new IrReturn(R(_x)))),
      Function("DivMod", IrType.Void, [_x, _y], new IrReturn(null))
    ]);
    var file = PythonEmitter.Emit(module).Single();
    Assert.That(file.Path, Is.EqualTo("adler32.py"));
    Assert.That(file.Content, Does.StartWith("# Hawkynt.Checksums.Adler32: generated by polypiler. Change the source, not this file.\n# Python profile: py3.14.\n\n__all__ = [\"compute_checksum\", \"div_mod\"]\n"));
    Assert.That(file.Content, Does.Contain("\n\n\ndef compute_checksum(data: list[int]) -> int:\n    return _helper(len(data))\n"));
    Assert.That(file.Content, Does.Contain("def _helper(x: int) -> int:").And.Contain("def div_mod(x: int, y: int) -> None:\n    pass\n"));
    Assert.That(PythonEmitter.FileName(module), Is.EqualTo("adler32.py"));
    Assert.That(PythonEmitter.FunctionNames(module), Is.EqualTo(new Dictionary<string, string> { ["computeChecksum"] = "compute_checksum", ["Helper"] = "_helper", ["DivMod"] = "div_mod" }));
  }

