  [Test]
  public void Header_NamesTheProfileTheHelpersLicenceAndTheFloatingPointMode() {
    var x = L("x", IrType.F64);
    var module = Returning(IrType.F64, [x], Bin(IrBinaryOp.Divide, R(x), R(x)));
    var text = PythonEmitter.Emit(module, PythonProfile.Parse("py3.11"), FloatMode.Strict, null, TargetPassOptions.None).Files.Single().Content;
    Assert.That(text, Does.StartWith("# M: generated by polypiler. Change the source, not this file.\n# Python profile: py3.11.\n# Helpers added by polypiler: MIT"));
    Assert.That(text, Does.Contain("# Floating point: strict (ADR 0005)."));
    var helpers = PythonEmitter.Emit(module).Single().Helpers;
    Assert.That(helpers.Select(helper => (helper.Symbol, helper.Licence, helper.CallSites)), Is.EqualTo(new[] { ("_ply_fdiv", "MIT", 1) }));
    Assert.That(PythonEmitter.HelperOrigins["_ply_fdiv"], Is.EqualTo(("MIT", "Hawkynt/Polypiler:Polypiler.Core.Backends.Python/Helpers")));
  }

