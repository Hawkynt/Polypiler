  [Test]
  public void Locals_AvoidReservedAndModuleNames_AndOneNameOfTwoTypesIsTwoNames() {
    var len = L("len", IrType.I32);
    var shadow = L("f", IrType.I32);
    var twin = L("x", IrType.F64);
    var module = new IrModule("M", [Function("f", IrType.I32, [len], new IrDeclare(shadow, R(len)), new IrDeclare(twin, C(IrType.F64, BitConverter.DoubleToInt64Bits(1.0))),
