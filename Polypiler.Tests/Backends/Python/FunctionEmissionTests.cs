  [Test]
  public void ConstantsAndGlobals_OfTheModule() {
    var scalar = new IrModuleConst("limit", IrType.I32, [5]);
    var table = new IrModuleConst("crcTable", IrType.Array(IrType.U32), [.. Enumerable.Range(0, 9).Select(value => (long)value)]);
    var counter = new IrGlobal("callCount", IrType.I32, null);
    var seeded = new IrGlobal("seed", IrType.U64, new IrCall("Seed", IrType.U64, []));
    var module = new IrModule("M", [
      Function("Count", IrType.I32, [], new IrGlobalAssign(counter, Bin(IrBinaryOp.Add, new IrGlobalRef(counter), new IrConstRef(scalar))),
        new IrReturn(new IrConvert(IrType.I32, new IrArrayLoad(new IrConstRef(table), new IrArrayLength(new IrConstRef(table)))))),
      Function("Seed", IrType.U64, [], new IrReturn(C(IrType.U64, 7))),
      Function("Read", IrType.U64, [], new IrReturn(new IrGlobalRef(seeded)))
    ], [scalar, table]) { Globals = [counter, seeded] };
    var text = Emit(module);
    Assert.That(text, Does.Contain("\n\n\n_LIMIT: int = 5\n_CRC_TABLE = (\n    0, 1, 2, 3, 4, 5, 6, 7,\n    8,\n)\n"));
    Assert.That(text, Does.Contain("def count() -> int:\n    global _call_count\n    _call_count = (((_call_count + _LIMIT) & 0xFFFFFFFF) ^ 0x80000000) - 0x80000000\n    return ((_CRC_TABLE[len(_CRC_TABLE)] & 0xFFFFFFFF) ^ 0x80000000) - 0x80000000\n"));
    Assert.That(text, Does.EndWith("def read() -> int:\n    return _seed\n\n\n_call_count: int = 0\n_seed: int = seed()\n"));
  }

  [Test]
  public void Arrays_AreLists_WithChecksWherePythonWouldCountFromTheEnd() {
    var module = new IrModule("M", [
      Function("Make", IrType.Array(IrType.F32), [_x], new IrReturn(new IrNewArray(IrType.Array(IrType.F32), R(_x)))),
      Function("Flags", IrType.Array(IrType.U8), [], new IrReturn(new IrNewArray(IrType.Array(IrType.U8), I(2)))),
      Function("Fixed", IrType.Array(IrType.I32), [], new IrReturn(new IrNewArray(IrType.Array(IrType.I32), I(3)))),
