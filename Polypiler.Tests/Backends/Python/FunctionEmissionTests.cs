  [Test]
  public void CollidingExports_AreRefused_AndNoFileIsWritten() {
    var module = new IrModule("M", [Function("compute_checksum", IrType.I32, [], new IrReturn(I(1))), Function("ComputeChecksum", IrType.I32, [], new IrReturn(I(2)))]);
    Assert.That(Problems(module), Is.EqualTo(new[] { "error PLY1874: exports 'compute_checksum' and 'ComputeChecksum' both map to the Python name 'compute_checksum'" }));
    Assert.That(() => PythonEmitter.Emit(module), Throws.ArgumentException.With.Message.Contains("PLY1874").Or.Message.Contains("compute_checksum"));
    var nameless = new IrModule("M", [Function("$", IrType.I32, [], new IrReturn(I(1)))]);
    Assert.That(Problems(nameless), Is.EqualTo(new[] { "error PLY1874: export '$' has no valid Python name" }));
  }

  [Test]
  public void PrivateNames_TakeTheNextFreeName_AndAvoidTheHelpers() {
    var module = new IrModule("M", [
