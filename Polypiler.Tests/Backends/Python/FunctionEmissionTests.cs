    Assert.That(text, Does.Contain("return [0] * 3\n").And.Contain("return [x, 2]\n"));
  }

  [Test]
  public void Stores_ComputeThePlaceFirstWhereTheValueCanTrap() {
    var data = L("data", IrType.Array(IrType.I32));
    var other = L("other", IrType.Array(IrType.I32));
    var module = new IrModule("M", [
      Function("Put", IrType.Void, [data, _x], new IrStore(R(data), R(_x), Bin(IrBinaryOp.Add, R(_x), I(1))), new IrReturn(null)),
      Function("Trap", IrType.Void, [data, other, _x],
        new IrStore(new IrConditional(Bin(IrBinaryOp.Less, R(_x), I(0)), R(data), R(other)), Bin(IrBinaryOp.Add, R(_x), I(1)), Bin(IrBinaryOp.Divide, I(1), R(_x))),
        new IrStore(new IrConditional(Bin(IrBinaryOp.Less, R(_x), I(0)), R(data), R(other)), I(0), R(_x)),
        new IrReturn(null))
    ]);
    var text = Emit(module);
    Assert.That(text, Does.Contain("def put(data: list[int], x: int) -> None:\n    data[_ply_index(x)] = (((x + 1) & 0xFFFFFFFF) ^ 0x80000000) - 0x80000000\n"));
    Assert.That(text, Does.Contain("    _t1 = data if x < 0 else other\n    _t2 = (((x + 1) & 0xFFFFFFFF) ^ 0x80000000) - 0x80000000\n    _t1[_ply_index(_t2)] = _ply_sdiv(1, x, -2147483648)\n"));
    Assert.That(text, Does.Contain("    (data if x < 0 else other)[0] = x\n"));
  }

  [Test]
  public void Steps_AsStatementsAndAsValues() {
    var data = L("data", IrType.Array(IrType.I64));
    var number = L("d", IrType.F32);
    var module = new IrModule("M", [
      Function("Statements", IrType.Void, [data, _x, number],
        new IrExprStmt(new IrStep(R(_x), true, true, false)),
        new IrExprStmt(new IrStep(R(number), false, false, false)),
        new IrExprStmt(new IrStep(new IrArrayLoad(R(data), R(_x)), true, false, true)),
        new IrExprStmt(new IrStep(new IrArrayLoad(R(data), I(0)), false, false, false)),
        new IrExprStmt(new IrStep(new IrArrayLoad(new IrConditional(Bin(IrBinaryOp.Less, R(_x), I(0)), R(data), R(data)), Bin(IrBinaryOp.Add, R(_x), I(1))), true, false, false)),
        new IrReturn(null)),
      Function("Values", IrType.I32, [data, _x],
        new IrDeclare(_y, Bin(IrBinaryOp.Add, new IrStep(R(_x), true, false, false), new IrStep(R(_x), false, true, true))),
        new IrReturn(Bin(IrBinaryOp.Add, R(_y), new IrConvert(IrType.I32, Bin(IrBinaryOp.Add, new IrStep(new IrArrayLoad(R(data), R(_x)), true, true, false), new IrStep(new IrArrayLoad(R(data), I(1)), true, false, false))))))
    ]);
    var text = Emit(module);
    Assert.That(text, Does.Contain("    x = (((x + 1) & 0xFFFFFFFF) ^ 0x80000000) - 0x80000000\n    d = _ply_f32(d - 1.0)\n"));
    Assert.That(text, Does.Contain("    data[x] = _ply_checked(data[_ply_index(x)] + 1, -9223372036854775808, 9223372036854775807)\n"));
    Assert.That(text, Does.Contain("    data[0] = (((data[0] - 1) & 0xFFFF_FFFF_FFFF_FFFF) ^ 0x8000_0000_0000_0000) - 0x8000_0000_0000_0000\n"));
    Assert.That(text, Does.Contain("    _t1 = data if x < 0 else data\n    _t2 = (((x + 1) & 0xFFFFFFFF) ^ 0x80000000) - 0x80000000\n    _t1[_t2] = "));
    Assert.That(text, Does.Contain("(x := (((x + 1) & 0xFFFFFFFF) ^ 0x80000000) - 0x80000000) + (x, (x := _ply_checked(x - 1, -2147483648, 2147483647)))[0]"));
    Assert.That(text, Does.Contain("((_t1 := data), (_t2 := x), (_t3 := _t1[_ply_index(_t2)]), (_t4 := (((_t3 + 1) & 0xFFFF_FFFF_FFFF_FFFF) ^ 0x8000_0000_0000_0000) - 0x8000_0000_0000_0000), _t1.__setitem__(_t2, _t4))[2]"));
    Assert.That(text, Does.Contain("_t5.__setitem__(_t6, _t8))[3]"));
  }

  [Test]
  public void ALibraryExceptionThrown_IsTheBuiltInExceptionOfTheTrapTable() {
    IrStmt Throw(IrClassType type, params IrExpr[] arguments) => new IrThrow(new IrNew(IrType.Object(type), IrExceptionClass.Constructor(type, arguments.Length), arguments));
    var module = new IrModule("M", [Function("f", IrType.Void, [_x],
      new IrIf(Bin(IrBinaryOp.Equal, R(_x), I(0)), Block(Throw(IrExceptionClass.OverflowException, new IrStrConst("integer overflow"))), null),
      new IrIf(Bin(IrBinaryOp.Equal, R(_x), I(1)), Block(Throw(IrExceptionClass.ArithmeticException)), null),
      new IrIf(Bin(IrBinaryOp.Equal, R(_x), I(2)), Block(Throw(IrExceptionClass.DivideByZeroException)), null),
      new IrIf(Bin(IrBinaryOp.Equal, R(_x), I(3)), Block(Throw(IrExceptionClass.IndexOutOfRangeException)), null),
      new IrIf(Bin(IrBinaryOp.Equal, R(_x), I(4)), Block(Throw(IrExceptionClass.NullReferenceException)), null),
      new IrIf(Bin(IrBinaryOp.Equal, R(_x), I(5)), Block(Throw(IrExceptionClass.InvalidCastException)), null),
      new IrIf(Bin(IrBinaryOp.Equal, R(_x), I(6)), Block(Throw(IrExceptionClass.InvalidOperationException)), null),
      new IrIf(Bin(IrBinaryOp.Equal, R(_x), I(7)), Block(Throw(IrExceptionClass.KeyNotFoundException)), null),
      new IrIf(Bin(IrBinaryOp.Equal, R(_x), I(8)), Block(Throw(IrExceptionClass.ArgumentOutOfRangeException)), null),
      new IrIf(Bin(IrBinaryOp.Equal, R(_x), I(10)), Block(Throw(IrExceptionClass.FormatException)), null),
      new IrIf(Bin(IrBinaryOp.Equal, R(_x), I(11)), Block(Throw(IrExceptionClass.ArgumentException)), null),
      new IrIf(Bin(IrBinaryOp.Equal, R(_x), I(9)), Block(Throw(IrExceptionClass.Exception)), null),
      new IrReturn(null))]);
    var text = Emit(module);
    foreach (var raised in new[] { "OverflowError(\"integer overflow\")", "ArithmeticError(", "ZeroDivisionError(", "IndexError(", "AttributeError(", "InvalidCastError(", "RuntimeError(", "KeyError(", "ArgumentOutOfRangeError(", "FormatError(", "ValueError(", "Exception(" })
      Assert.That(text, Does.Contain("raise " + raised));

    // The classes of the library that are no built-in exception derive from the one of the nearest meaning.
    Assert.That(text, Does.Contain("class ArgumentOutOfRangeError(ValueError):")
      .And.Contain("class FormatError(ValueError):").And.Contain("class InvalidCastError(TypeError):"));
  }

