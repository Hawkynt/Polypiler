  [Test]
  public void Writes_OnlyTheSquareRootOfTheFloatingPointTable() {
    var x = L("x", IrType.F64);
    Assert.That(PythonEmitter.Writes(new IrIntrinsic(IrIntrinsicOp.Sqrt, IrType.F64, [R(x)])), Is.True);
    Assert.That(PythonEmitter.Writes(new IrIntrinsic(IrIntrinsicOp.Sin, IrType.F64, [R(x)])), Is.False);
    Assert.That(PythonEmitter.Writes(new IrIntrinsic(IrIntrinsicOp.FusedMultiplyAdd, IrType.F64, [R(x), R(x), R(x)])), Is.False);
    Assert.That(PythonEmitter.Writes(new IrIntrinsic(IrIntrinsicOp.FloatBits, IrType.I64, [R(x)])), Is.True);
  }

  [Test]
  public void UnusedDeclarations_AreRemovedByO0501_AndNothingElse() {
    var helper = PythonSyntaxReader.ReadModule("import math\nimport struct\n\n\ndef _a() -> float:\n    return math.pi\n\n\ndef _b() -> int:\n    return 1\n\n\ndef f() -> int:\n    return _b()\n");
    var marked = helper with { Body = [.. helper.Body.Select(statement => statement is PyFunctionDef { Name: "_a" or "_b" } function ? function with { IsHelper = true } : statement)] };
    var applied = new List<string>();
    var result = new PythonUnusedDeclarations().Run(marked, PythonProfile.Default, applied.Add);
    Assert.That(result.Body.Select(statement => statement is PyFunctionDef function ? function.Name : statement.GetType().Name), Is.EqualTo(new[] { "_b", "f" }));
    Assert.That(applied, Is.EqualTo(new[] { "removed the helper _a, which nothing calls", "removed the import of math, which nothing uses", "removed the import of struct, which nothing uses" }));
    Assert.That(new PythonUnusedDeclarations().Run(result, PythonProfile.Default, applied.Add), Is.SameAs(result));
    Assert.That(PythonTargetPasses.Pipeline.Ids, Is.EqualTo(new[] { "O0501" }));
    Assert.That(new PythonUnusedDeclarations().Name, Is.EqualTo("unused declaration removal"));
    Assert.That(() => new PythonUnusedDeclarations().Run(null!, PythonProfile.Default, applied.Add), Throws.ArgumentNullException);
  }

  [Test]
  public void Build_GivesTheTreeThatIsPrinted() {
    var module = Returning(IrType.I32, [_x], R(_x));
    var built = PythonEmitter.Build(module, PythonProfile.Default, FloatMode.Accurate, null, TargetPassOptions.Default);
    Assert.That(Polypiler.Core.Backends.Python.Printing.PythonPrinter.Print(built.Tree), Is.EqualTo(Emit(module)));
    Assert.That(PythonEmitter.LegalizeHelpers(module, () => throw new InvalidOperationException("not needed"), PythonProfile.Default), Is.SameAs(module));
  }

