using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using NUnit.Framework;
using Polypiler.Cli;
using Polypiler.Core;
using Polypiler.Core.Verification.Manifests;
using Polypiler.Core.Backends.JavaScript;
using Polypiler.Prototype.Testing;

namespace Polypiler.Tests.Backends.JavaScript;

/// <summary>
/// The options of <c>translate</c> that name the JavaScript to write, run inside the test process.
/// The acceptance tests start the real executable and run what it writes.
/// </summary>
[TestFixture]
public sealed class TranslateToJavaScriptProfileTests {

  private const string Method = "public static long F(int a) { long b = a; return b * b; }";

  private string _directory = "";
  private string _out = "";

  [SetUp]
  public void CreateWorkingDirectory() {
    this._directory = Path.Combine(Path.GetTempPath(), "polypiler-" + Guid.NewGuid().ToString("N"));
    this._out = Path.Combine(this._directory, "out");
    Directory.CreateDirectory(this._directory);
  }

  [TearDown]
  public void DeleteWorkingDirectory() => Directory.Delete(this._directory, true);

  private (int ExitCode, string Output, string Error) Translate(string to, params string[] options) {
    var source = Path.Combine(this._directory, "Snippet.cs");
    File.WriteAllText(source, PrototypeFixture.Wrap(Method));
    using var output = new StringWriter();
    using var error = new StringWriter();
    string[] arguments = ["translate", source, "--from", "csharp", "--to", to, .. options, "--output", this._out];
    var exitCode = Program.Run(arguments, output, error);
    return (exitCode, output.ToString(), error.ToString());
  }

  /// <summary>Every profile the command line can name: the file it writes, and the profile that file states.</summary>
  [TestCase(new string[0], "Snippet.mjs", "es2022, esm")]
  [TestCase(new[] { "--profile", "es2022" }, "Snippet.mjs", "es2022, esm")]
  [TestCase(new[] { "--module", "cjs" }, "Snippet.cjs", "es2022, cjs")]
  [TestCase(new[] { "--module", "iife", "--global", "Lib" }, "Snippet.js", "es2022, iife as the global Lib")]
  [TestCase(new[] { "--profile", "es2020", "--module", "esm" }, "Snippet.mjs", "es2020, esm")]
  [TestCase(new[] { "--profile", "es2017" }, "Snippet.mjs", "es2017, esm")]
  [TestCase(new[] { "--module", "cjs", "--profile", "es2015" }, "Snippet.cjs", "es2015, cjs")]
  [TestCase(new[] { "--profile", "es2015", "--typed-arrays" }, "Snippet.mjs", "es2015, esm")]
  [TestCase(new[] { "--profile", "es5" }, "Snippet.cjs", "es5, cjs")]
  [TestCase(new[] { "--profile", "es5", "--module", "cjs" }, "Snippet.cjs", "es5, cjs")]
  [TestCase(new[] { "--typed-arrays", "--profile", "es5" }, "Snippet.cjs", "es5 with typed arrays, cjs")]
  [TestCase(new[] { "--profile", "es5", "--global", "$lib", "--module", "iife", "--typed-arrays" }, "Snippet.js", "es5 with typed arrays, iife as the global $lib")]
  public void Profile_ChoosesTheFileAndIsStatedInIt(string[] options, string file, string stated) {
    var path = Path.Combine(this._out, file);
    var (exitCode, output, error) = this.Translate("javascript", options);
    Assert.That((exitCode, error), Is.EqualTo(((int)ExitCode.Success, "")));
    Assert.That(output.Trim(), Is.EqualTo(path));
    Assert.That(Directory.GetFiles(this._out), Is.EquivalentTo(new[] { path, Path.Combine(this._out, Manifest.FileName) }));

    var text = File.ReadAllText(path);
    Assert.That(text, Does.StartWith($"// Snippet: generated by polypiler. Change the source, not this file.\n// JavaScript profile: {stated}.\n"));
    Assert.That(text.Contains("BigInt"), Is.EqualTo(stated.StartsWith("es202", StringComparison.Ordinal)));
    var profile = JavaScriptProfile.Parse(
      stated[..stated.IndexOfAny([',', ' '])], Path.GetExtension(file) switch { ".mjs" => "esm", ".cjs" => "cjs", _ => "iife" },
      stated.Contains("global") ? stated[(stated.LastIndexOf(' ') + 1)..] : null, stated.Contains("typed"));
    Assert.That(GeneratedJavaScript.Problems(text, profile), Is.Empty);
  }

  /// <summary>A flag is the last word of a command line as well as any other.</summary>
  [Test]
  public void TypedArrays_TakesNoValue() {
    var source = Path.Combine(this._directory, "Snippet.cs");
    File.WriteAllText(source, PrototypeFixture.Wrap("public static int F(int[] a) => a[0];"));
    using var output = new StringWriter();
    using var error = new StringWriter();
    Assert.That(Program.Run(["translate", source, "--from", "csharp", "--to", "javascript", "--output", this._out, "--profile", "es5", "--typed-arrays"], output, error), Is.Zero, error.ToString());
    Assert.That(File.ReadAllText(Path.Combine(this._out, "Snippet.cjs")), Does.Contain("// F(a: Int32Array): number"));
  }

  /// <summary>Test design 8: what names no profile is PLY0003, exit code 2, and nothing is written.</summary>
  [TestCase(new[] { "--profile", "es3" }, "unknown JavaScript profile 'es3'; the profiles are 'es5', 'es2015', 'es2017', 'es2020', 'es2022'")]
  [TestCase(new[] { "--profile", "es2016" }, "unknown JavaScript profile 'es2016'")]
  [TestCase(new[] { "--module", "amd" }, "unknown module format 'amd'; the module formats are 'esm', 'cjs', 'iife'")]
  [TestCase(new[] { "--profile", "es5", "--module", "esm" }, "the profile 'es5' has no ES modules; its module formats are 'cjs' and 'iife'")]
  [TestCase(new[] { "--module", "iife" }, "the module format 'iife' needs the name of its global object: --global <name>")]
  [TestCase(new[] { "--profile", "es5", "--module", "iife" }, "the module format 'iife' needs the name of its global object: --global <name>")]
  [TestCase(new[] { "--global", "Lib" }, "a global object belongs to the module format 'iife', not to 'esm'")]
  [TestCase(new[] { "--module", "iife", "--global", "2fast" }, "'2fast' is not a name a JavaScript global can have")]
  [TestCase(new[] { "--module", "iife", "--global", "my-lib" }, "'my-lib' is not a name a JavaScript global can have")]
  [TestCase(new[] { "--module", "iife", "--global", "class" }, "'class' is not a name a JavaScript global can have")]
  public void InvalidProfile_IsAUsageError(string[] options, string message) {
    var (exitCode, output, error) = this.Translate("javascript", options);
    Assert.That((exitCode, output), Is.EqualTo(((int)ExitCode.UsageError, "")));
    Assert.That(error, Does.StartWith("polypiler: error PLY0003: " + message).And.Not.Contain("usage:"));
    Assert.That(Directory.Exists(this._out), Is.False);
  }

  /// <summary>The options of the JavaScript backend belong to it alone, and an option that takes a value needs one.</summary>
  [TestCase(new[] { "--module", "cjs" }, "the option '--module' does not apply to the target language 'csharp'")]
  [TestCase(new[] { "--global", "Lib" }, "the option '--global' does not apply to the target language 'csharp'")]
  [TestCase(new[] { "--typed-arrays" }, "the option '--typed-arrays' does not apply to the target language 'csharp'")]
  public void ProfileOption_DoesNotApplyToAnotherTarget(string[] options, string message) {
    var (exitCode, output, error) = this.Translate("csharp", options);
    Assert.That((exitCode, output), Is.EqualTo(((int)ExitCode.UsageError, "")));
    Assert.That(error, Does.StartWith("polypiler: error PLY0003: " + message));
    Assert.That(Directory.Exists(this._out), Is.False);
  }

  /// <summary>
  /// <c>--profile</c> is one option of the command that the chosen target reads its own way: a
  /// JavaScript level is no C# profile and a C# framework no JavaScript level, and each target says
  /// so with its own list. <c>--langversion</c> stays the C# backend's.
  /// </summary>
  [TestCase("csharp", new[] { "--profile", "es2017" }, "unknown C# profile 'es2017'; the profiles are 'net2.0'")]
  [TestCase("javascript", new[] { "--profile", "net8.0" }, "unknown JavaScript profile 'net8.0'; the profiles are 'es5', 'es2015', 'es2017', 'es2020', 'es2022'")]
  [TestCase("javascript", new[] { "--langversion", "14" }, "the option '--langversion' does not apply to the target language 'javascript'")]
  public void SharedProfileOption_IsReadByTheChosenTarget(string to, string[] options, string message) {
    var (exitCode, output, error) = this.Translate(to, options);
    Assert.That((exitCode, output), Is.EqualTo(((int)ExitCode.UsageError, "")));
    Assert.That(error, Does.StartWith("polypiler: error PLY0003: " + message));
    Assert.That(Directory.Exists(this._out), Is.False);
  }

  /// <summary>The same option names a profile of either target, and each target writes for its own.</summary>
  [Test]
  public void SharedProfileOption_ChoosesTheProfileOfEitherTarget() {
    Assert.That(this.Translate("csharp", "--profile", "net8.0").ExitCode, Is.EqualTo((int)ExitCode.Success));
    Assert.That(this.Translate("javascript", "--profile", "es2017").ExitCode, Is.EqualTo((int)ExitCode.Success));
    Assert.That(Directory.GetFiles(this._out).Select(Path.GetFileName), Is.EquivalentTo(new[] { "Snippet.cs", "Snippet.mjs", Manifest.FileName }));
    Assert.That(File.ReadAllText(Path.Combine(this._out, "Snippet.mjs")), Does.Contain("// JavaScript profile: es2017, esm."));
    using var help = new StringWriter();
    Program.Run(["translate", "--help"], help, TextWriter.Null);
    Assert.That(help.ToString().Split("  --profile ").Length, Is.EqualTo(2), "listed once");
  }

  [TestCase("--profile")]
  [TestCase("--module")]
  [TestCase("--global")]
  public void ProfileOption_NeedsAValue(string option) {
    using var output = new StringWriter();
    using var error = new StringWriter();
    Assert.That(Program.Run(["translate", "A.cs", "--from", "csharp", "--to", "javascript", "--output", this._out, option], output, error), Is.EqualTo((int)ExitCode.UsageError));
    Assert.That(error.ToString(), Is.EqualTo($"polypiler: error PLY0003: option '{option}' requires a value{Environment.NewLine}"));
  }

  [Test]
  public void Help_NamesTheProfileOptions() {
    using var help = new StringWriter();
    Program.Run(["translate", "--help"], help, TextWriter.Null);
    Assert.That(help.ToString(), Does.Contain("  --profile <name> ").And.Contain("  --module <esm|cjs|iife> ").And.Contain("  --global <name> ").And.Contain("  --typed-arrays "));
  }

  /// <summary>
  /// Test design 9: a construct that has no form in the chosen profile is PLY1152, exit code 3, and
  /// nothing is written. The standard table has a form for everything, so the command is given a
  /// table that lacks the replacement of <c>BigInt</c>.
  /// </summary>
  [Test]
  public void ConstructWithoutAForm_IsExitCode3AndWritesNothing() {
    var source = Path.Combine(this._directory, "Snippet.cs");
    File.WriteAllText(source, PrototypeFixture.Wrap(Method));
    var table = JavaScriptCapabilities.Standard.With(new("BigInt", 2020));
    string[] arguments = [source, "--from", "csharp", "--to", "javascript", "--output", this._out, "--profile", "es2017"];
    using var output = new StringWriter();
    using var error = new StringWriter();
    Assert.That(TranslateCommand.Run(arguments, output, error, table), Is.EqualTo(TranslateCommand.UnsupportedConstruct));
    Assert.That((TranslateCommand.UnsupportedConstruct, output.ToString()), Is.EqualTo((3, "")));
    Assert.That(error.ToString().Split('\n', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries), Is.EqualTo(new[] {
      "polypiler: error PLY1152: 'the function 'F'' cannot be expressed in JavaScript profile 'es2017'",
      "polypiler: error PLY1152: 'Convert' cannot be expressed in JavaScript profile 'es2017'",
      "polypiler: error PLY1152: 'Multiply' cannot be expressed in JavaScript profile 'es2017'",
      "polypiler: 3 error(s), 0 warning(s)"
    }));
    Assert.That(Directory.Exists(this._out), Is.False);

    using var written = new StringWriter();
    Assert.That(TranslateCommand.Run([.. arguments[..^1], "es2020"], written, error, table), Is.EqualTo((int)ExitCode.Success), "the level that has BigInt needs no replacement");
    Assert.That(written.ToString().Trim(), Is.EqualTo(Path.Combine(this._out, "Snippet.mjs")));
    Assert.That(TranslateCommand.Run(arguments, written, error), Is.EqualTo((int)ExitCode.Success), "the standard table has the replacement");
  }

  /// <summary>A module that is already IR is written for the profile its options name.</summary>
  [Test]
  public void Emit_FollowsTheProfileOptions() {
    var module = PrototypeFixture.Import("Snippet.cs", PrototypeFixture.Wrap(Method));
    using var output = new StringWriter();
    using var error = new StringWriter();
    var options = new Dictionary<string, string> { ["--to"] = "javascript", ["--output"] = this._out, ["--profile"] = "es5", ["--module"] = "iife", ["--global"] = "Lib", ["--typed-arrays"] = "" };
    Assert.That(TranslateCommand.Emit(module, options, output, error), Is.EqualTo((int)ExitCode.Success), error.ToString());
    Assert.That(File.ReadAllText(Path.Combine(this._out, "Snippet.js")), Does.Contain("// JavaScript profile: es5 with typed arrays, iife as the global Lib.\n").And.Contain("\nvar Lib = (function () {\n"));
  }

}
