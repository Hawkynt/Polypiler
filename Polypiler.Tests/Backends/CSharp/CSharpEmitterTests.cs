  /// <summary>
  /// Test design 11: every contextual keyword as the name of a method, of its parameter and of a
  /// local, at the start of a statement and inside an expression — unescaped, and still the same program.
  /// </summary>
  [Test]
  public void ContextualKeywords_StayReadableNames() {
    IrExpr Ref(IrLocal local) => new IrLocalRef(local);
    IrExpr Mixed(IrExpr total, IrExpr next) => Op(IrBinaryOp.Add, Op(IrBinaryOp.Multiply, total, Int(31)), next);
    var locals = _contextual.Select(name => new IrLocal(name, IrType.I32)).ToArray();
    var x = new IrLocal("x", IrType.I32);
    var total = new IrLocal("total", IrType.I32);
    var variables = new IrModule("Variables", [
      Function("Parameters", IrType.I32, locals, [
        .. locals.Select(local => new IrAssign(local, Op(IrBinaryOp.Xor, Ref(local), Int(local.Name.Length)))),
        new IrReturn(locals.Select(Ref).Aggregate(Mixed))
      ]),
      Function("Locals", IrType.I32, [x], [
        .. locals.Select(local => new IrDeclare(local, Op(IrBinaryOp.Add, Ref(x), Int(local.Name.Length)))),
        .. locals.Select(local => new IrAssign(local, Op(IrBinaryOp.Xor, Ref(local), Ref(x)))),
        new IrReturn(locals.Select(Ref).Aggregate(Mixed))
      ])
    ]);
    var methods = new IrModule("Methods", [
      .. locals.Select(local => Function(local.Name, IrType.I32, [x], new IrReturn(Op(IrBinaryOp.Add, Ref(x), Int(local.Name.Length))))),
      Function("All", IrType.I32, [x], [
        .. locals.Select(local => new IrExprStmt(new IrCall(local.Name, IrType.I32, [Ref(x)]))),
        new IrDeclare(total, Int(0)),
        .. locals.Select(local => new IrAssign(total, Mixed(Ref(total), new IrCall(local.Name, IrType.I32, [Ref(x)])))),
        new IrReturn(Ref(total))
      ])
    ]);
    Assert.That(Emit(variables), Does.Not.Contain("@").And.Contain(", int value, int var, ").And.Contain("\n      yield = yield ^ x;\n"));
    Assert.That(Emit(methods), Does.Not.Contain("@").And.Contain("public static int await(int x) => unchecked(x + 5);").And.Contain("\n      await(x);\n"));

    object[] arguments = Enumerable.Range(1, locals.Length).Cast<object>().ToArray();
    (IrModule Module, PrototypeCall Call)[] runs = [
      (variables, new PrototypeCall("Parameters", arguments)),
      (variables, new PrototypeCall("Locals", [7])),
      (methods, new PrototypeCall("All", [7])),
      (methods, new PrototypeCall("nameof", [7]))
    ];
    foreach (var (module, call) in runs)
      Assert.That(Compiled(module, call), Is.EqualTo(PrototypeFixture.InterpretedOutcome(module, call)), call.ToString());
  }

