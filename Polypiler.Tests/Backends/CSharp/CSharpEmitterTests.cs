  private static readonly bool[] _overflowChecking = [false, true];

  private static IrModule Import(string methods) => PrototypeFixture.Import("Snippet.cs", PrototypeFixture.Wrap(methods));

  private static string Emit(IrModule module, string? @namespace = null) => CSharpEmitter.Emit(module, @namespace).Single().Content;

  /// <summary>The statements of the function <c>F</c>, one per line, without indentation and without the <c>unchecked</c> block around them.</summary>
  private static string[] Body(string methods) => EmittedCSharp.Body(Emit(Import(methods)));

  /// <summary>The module as the C# compiler builds its generated text, without and with overflow checking.</summary>
  private static List<GeneratedCSharp> Builds(IrModule module) {
    var text = Emit(module);
    return _overflowChecking.Select(checking => GeneratedCSharp.Compile(text, checking)).ToList();
  }

  /// <summary>The outcome of a call in the compiled output, which must not depend on the overflow setting.</summary>
  private static string Compiled(List<GeneratedCSharp> builds, PrototypeCall call) {
    var outcomes = builds.Select(build => build.Outcome(call)).Distinct().ToList();
    Assert.That(outcomes, Has.Count.EqualTo(1), $"{call} depends on CheckOverflow");
    return outcomes[0];
  }

  private static string Compiled(IrModule module, PrototypeCall call) => Compiled(Builds(module), call);

