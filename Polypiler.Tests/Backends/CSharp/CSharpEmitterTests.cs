      Function("FixedLength", IrType.I32, [], new IrReturn(new IrArrayLength(new IrNewArray(IrType.Array(IrType.U8), Int(3))))),
      Function("ElementOfANewArray", IrType.U32, [a], new IrReturn(new IrArrayLoad(new IrNewArray(IrType.Array(IrType.U32), Ref(a)), Int(0)))),
      Function("Discarded", IrType.Void, [a, d],
