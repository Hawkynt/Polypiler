  /// <summary>A node kind, an operator and a type the backend has never heard of, as a later IR may add them.</summary>
  private sealed record Mystery(IrType Type) : IrExpr(Type);

  private sealed record Riddle : IrStmt;

  private static IrType Unheard { get; } = (IrType)Activator.CreateInstance(
    typeof(IrType), BindingFlags.Instance | BindingFlags.NonPublic, null, [(IrTypeKind)99, null], null)!;

  private static IEnumerable<TestCaseData> UnknownConstructs() {
    var a = new IrLocal("a", IrType.I32);
    var odd = new IrLocal("odd", Unheard);
    var mystery = new Mystery(IrType.I32);
    IrModule Of(params IrStmt[] body) => new("M", [Function("F", IrType.I32, [a], body)]);
    yield return new TestCaseData(Of(new IrReturn(mystery)), new[] { "Mystery" }).SetName("Unknown: an expression kind");
    yield return new TestCaseData(Of(new IrReturn(Op(IrBinaryOp.Add, new IrUnary(IrUnaryOp.Negate, mystery), Int(1)))), new[] { "Mystery" }).SetName("Unknown: an expression kind inside known ones");
    yield return new TestCaseData(Of(new Riddle(), new IrReturn(Int(1))), new[] { "Riddle" }).SetName("Unknown: a statement kind");
    yield return new TestCaseData(Of(new IrWhile(new IrConst(IrType.Bool, 1), new IrBlock([new IrIf(new IrConst(IrType.Bool, 1), new IrBlock([new Riddle()]), new IrBlock([new Riddle()]))]))), new[] { "Riddle" })
      .SetName("Unknown: a statement kind inside known ones, reported once");
    yield return new TestCaseData(Of(new IrReturn(new IrUnary((IrUnaryOp)99, new IrLocalRef(a)))), new[] { "99" }).SetName("Unknown: a unary operator");
    yield return new TestCaseData(Of(new IrReturn(Op((IrBinaryOp)98, new IrLocalRef(a), Int(1)))), new[] { "98" }).SetName("Unknown: a binary operator");
    yield return new TestCaseData(Of(new IrReturn(new IrConvert(IrType.I32, new IrConst(Unheard, 1)))), new[] { "99" }).SetName("Unknown: the type of an expression");
    yield return new TestCaseData(Of(new IrDeclare(odd, null), new IrReturn(Int(1))), new[] { "99" }).SetName("Unknown: the type of a local");
    yield return new TestCaseData(new IrModule("M", [new IrFunction("F", true, IrType.Void, [odd], [], new IrBlock([]))]), new[] { "99" }).SetName("Unknown: the type of a parameter");
    yield return new TestCaseData(new IrModule("M", [new IrFunction("F", true, IrType.Array(Unheard), [], [], new IrBlock([]))]), new[] { "99[]" }).SetName("Unknown: the element type of the returned array");
    yield return new TestCaseData(
      Of(new Riddle(), new IrExprStmt(new IrCall("F", IrType.I32, [mystery])), new IrStore(mystery, mystery, new IrArrayLength(new IrNewArray(IrType.Array(Unheard), mystery))), new IrAssign(a, new IrConditional(mystery, mystery, mystery))),
      new[] { "Riddle", "Mystery", "99[]" }).SetName("Unknown: several, each reported once in the order met");
  }

  /// <summary>Test design 9: what the backend does not know is refused as PLY1052 — before the verifier is asked — and nothing is emitted.</summary>
  [TestCaseSource(nameof(UnknownConstructs))]
  public void UnknownConstruct_IsRefused(IrModule module, string[] names) {
    var problems = CSharpEmitter.Check(module);
    Assert.That(problems.Select(problem => problem.ToString()),
      Is.EqualTo(names.Select(name => $"error PLY1052: '{name}' is not supported by the C# backend yet")));
    Assert.That(problems.Select(problem => (problem.Code, problem.Severity, problem.File)), Has.All.EqualTo((CSharpEmitter.Unsupported, DiagnosticSeverity.Error, (string?)null)));
    Assert.That(() => CSharpEmitter.Emit(module),
      Throws.ArgumentException.With.Message.Contains($"The module 'M' cannot be emitted: '{names[0]}' is not supported by the C# backend yet."));
  }

