        new IrExprStmt(new IrCall("FixedLength", IrType.I32, []))),
      Function("ByteChoice", IrType.U8, [c], new IrReturn(new IrConditional(Ref(c), new IrConst(IrType.U8, 1), new IrConst(IrType.U8, 200)))),
