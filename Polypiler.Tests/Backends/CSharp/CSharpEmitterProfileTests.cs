  /// <summary>
  /// Test design 4: a function is a method of the class in every profile, never a local function,
  /// and a helper never one either; a constant is written in decimal digits without separators in
  /// every profile, whatever the source wrote.
  /// </summary>
  [Test]
  public void NoProfile_WritesALocalFunctionOrANewerLiteral() {
    var module = Import(
      "private static uint Twice(uint a) => a + a; private const uint Mask = 0b1111_0000_1010_0101; "
      + "public static uint F(uint a) => System.Numerics.BitOperations.RotateLeft(Twice(a), 3) ^ Mask ^ 0x00FF_FF00 ^ 1_000_000;");
    foreach (var profile in CSharpProfile.All) {
      var text = Accepted(Emit(module, profile.Name), profile.Name);
      Assert.That(text, Does.Contain("\n  private static uint Twice(uint a)").And.Contain("\n  private const uint Mask = 61605;\n").And.Contain("16776960u").And.Contain("1000000u"));
      Assert.That(Regex.IsMatch(text, @"0[bB][01_]+|\d_\d"), Is.False, text);
      // Every method stands at the level of the class: two spaces, a modifier, and never inside another method.
      Assert.That(text.Split('\n').Where(line => line.Contains(" static ") && line.Contains('(')), Has.All.Matches<string>(line => Regex.IsMatch(line, @"^  (public|private) static ")), text);
      Assert.That(_overflowChecking.Select(checking => Run(text, checking, 0x12345678u)), Has.All.EqualTo(System.Numerics.BitOperations.RotateLeft(0x2468ACF0u, 3) ^ 61605u ^ 0x00FFFF00u ^ 1000000u));
    }
  }

