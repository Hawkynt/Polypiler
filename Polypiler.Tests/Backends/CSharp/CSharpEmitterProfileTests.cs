  /// <summary>
  /// Test design 4: a function that is one returned expression has an expression body from C# 6 on
  /// and a block before; wrap-around arithmetic stands in <c>unchecked</c> in either form.
  /// </summary>
  [TestCase("net3.5", null, "  public static int F(int a, int b) {|    unchecked {|      return a + b;|    }|  }")]
  [TestCase("net2.0", "5", "  public static int F(int a, int b) {|    unchecked {|      return a + b;|    }|  }")]
  [TestCase("net2.0", "6", "  public static int F(int a, int b) => unchecked(a + b);")]
  [TestCase("net4.6", null, "  public static int F(int a, int b) => unchecked(a + b);")]
  [TestCase("net10.0", null, "  public static int F(int a, int b) => unchecked(a + b);")]
  public void Body_IsAnExpressionFromCSharp6On(string profile, string? languageVersion, string expected) {
    var text = Emitted("public static int F(int a, int b) => a + b;", profile, languageVersion);
    Assert.That(text, Does.Contain("\n\n" + expected.Replace('|', '\n') + "\n\n}\n"));
