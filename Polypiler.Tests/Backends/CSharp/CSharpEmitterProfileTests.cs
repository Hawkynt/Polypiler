  /// <summary>
  /// Test design 4: an expression evaluated for its trap alone is assigned to the discard from C# 7
  /// on; before, a helper takes it and does nothing with it - and it still traps.
  /// </summary>
  [TestCase("net4.8", null, "_ = 1 / a;", false)]
  [TestCase("net4.6", "7", "_ = 1 / a;", false)]
  [TestCase("net4.6", null, "Ignore(1 / a);", true)]
  [TestCase("net2.0", null, "Ignore(1 / a);", true)]
  public void Discard_IsAHelperBeforeCSharp7(string profile, string? languageVersion, string expected, bool helper) {
    var a = new IrLocal("a", IrType.I32);
    var quotient = new IrBinary(IrBinaryOp.Divide, new IrConst(IrType.I32, 1), new IrLocalRef(a));
    var module = new IrModule("Snippet", [
      Function("F", IrType.I32, [a], new IrExprStmt(quotient), new IrSwitch(quotient, []), new IrReturn(new IrLocalRef(a)))
