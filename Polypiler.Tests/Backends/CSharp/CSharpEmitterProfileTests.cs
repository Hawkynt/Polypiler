    foreach (var checking in _overflowChecking) {
      Assert.That(Run(text, checking, 3), Is.EqualTo(3));
      Assert.That(() => Run(text, checking, 0), Throws.TargetInvocationException.With.InnerException.TypeOf<DivideByZeroException>());
    }
  }

