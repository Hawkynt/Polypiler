      "// Snippet: generated by polypiler. Change the source, not this file.",
      "// Profile: net4.8, C# 7.3.",
      "",
      "namespace Demo.Sums {",
      "",
      "  public static class Snippet {",
      "",
      "    public static uint Sum(byte[] data) {",
      "      unchecked {",
      "        uint sum = 0;",
      "        {",
      "          int _t1 = 0;",
      "          while (_t1 < data.Length) {",
      "            var b = data[_t1];",
      "            sum = sum + (uint)b;",
      "            _t1 = _t1 + 1;",
      "          }",
      "        }",
      "        return sum;",
      "      }",
      "    }",
      "",
      "  }",
      "",
      "}",
      "")));
  }

  /// <summary>The form of the namespace at the version that introduced the file-scoped one, just below it and where the version is raised.</summary>
  [TestCase("net10.0", null, "namespace Demo;", "public static class Snippet {")]
  [TestCase("net8.0", null, "namespace Demo;", "public static class Snippet {")]
  [TestCase("net4.8", "10", "namespace Demo;", "public static class Snippet {")]
  [TestCase("net4.8", "9", "namespace Demo {", "  public static class Snippet {")]
  [TestCase("netcoreapp3.1", null, "namespace Demo {", "  public static class Snippet {")]
  [TestCase("net2.0", null, "namespace Demo {", "  public static class Snippet {")]
  public void Namespace_FollowsTheLanguageVersion(string profile, string? languageVersion, string @namespace, string type) {
    var text = Accepted(Emit(PrototypeFixture.Imported("Adler32"), profile, languageVersion, "Demo"), profile, languageVersion);
    Assert.That(text.Split('\n')[3..6], Is.EqualTo(new[] { @namespace, "", type.Replace("Snippet", "Adler32") }));
    Assert.That(text, Does.Not.Contain(@namespace == "namespace Demo;" ? "namespace Demo {" : "namespace Demo;"));
    Assert.That(text.Split('\n'), Has.None.Matches<string>(line => line.Length > 0 && line.Trim().Length == 0));
    foreach (var checking in _overflowChecking) {
      var build = GeneratedCSharp.Compile(text, checking);
      Assert.That(build.ClassName, Is.EqualTo("Demo.Adler32"));
      Assert.That(build.Method("Compute").Invoke(null, [PrototypeCases.Text("Wikipedia")]), Is.EqualTo(300286872u));
    }
  }

  /// <summary>A keyword among the parts of a namespace is escaped in both forms, and a file without a namespace has neither.</summary>
  [Test]
  public void Namespace_IsEscapedInBothForms() {
