  /// <summary>The header of the file names the profile and the language version it was written for.</summary>
  [TestCase("net2.0", null, "// Profile: net2.0, C# 2.")]
  [TestCase("net4.8", null, "// Profile: net4.8, C# 7.3.")]
  [TestCase("net4.8", "9", "// Profile: net4.8, C# 9.")]
  [TestCase("net10.0", null, "// Profile: net10.0, C# 14.")]
  public void Header_NamesTheProfile(string profile, string? languageVersion, string expected) {
    var lines = Emit(Import("public static int F(int a) => a;"), profile, languageVersion).Split('\n');
    Assert.That(lines[..3], Is.EqualTo(new[] { "// Snippet: generated by polypiler. Change the source, not this file.", expected, "" }));
  }

  /// <summary>The default profile is the newest one, and the overload without a profile writes for it.</summary>
