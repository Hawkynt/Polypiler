/// <summary>
/// What the emitter writes differently from one profile to the next: the forms the language version
/// decides - the namespace, the body of a function, <c>var</c>, <c>&gt;&gt;&gt;</c>, the discard -
/// and the helpers a class gets where its framework lacks an API. The spelling is pinned at the
/// version where a form begins and at the one before it; that each file is C# of its profile is
/// decided by the C# compiler, against the profile's reference assemblies.
/// </summary>
[TestFixture]
public sealed class CSharpEmitterProfileTests {

  private static readonly bool[] _overflowChecking = [false, true];

  private static IrModule Import(string methods) => PrototypeFixture.Import("Snippet.cs", PrototypeFixture.Wrap(methods));

  private static string Emit(IrModule module, string profile, string? languageVersion = null, string? @namespace = null)
    => CSharpEmitter.Emit(module, CSharpProfile.Parse(profile, languageVersion), @namespace).Single().Content;

  /// <summary>The file as its profile's compiler accepts it, or the test fails with what it reports.</summary>
  private static string Accepted(string text, string profile, string? languageVersion = null) {
    Assert.That(GeneratedCSharp.ComplaintsFor(text, profile, CSharpProfile.Parse(profile, languageVersion).LanguageVersionName), Is.Empty, text);
    return text;
  }

  private static string Emitted(string methods, string profile, string? languageVersion = null)
    => Accepted(Emit(Import(methods), profile, languageVersion), profile, languageVersion);

  private static object? Run(string text, bool checking, params object[] arguments) => GeneratedCSharp.Compile(text, checking).Method("F").Invoke(null, arguments);

  private static IrFunction Function(string name, IrType returns, IrLocal[] parameters, params IrStmt[] body)
    => new(name, true, returns, parameters, body.OfType<IrDeclare>().Select(declare => declare.Local).ToList(), new IrBlock(body));

