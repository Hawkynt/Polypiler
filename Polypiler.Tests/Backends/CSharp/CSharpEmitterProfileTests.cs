      Assert.That(Run(text, checking, int.MaxValue, 1), Is.EqualTo(int.MinValue));
  }

  /// <summary>
  /// The expression body in its classes: nothing that wraps around needs no <c>unchecked</c>, a
  /// result that is checked as a whole sets its own context, a constant stands bare, and a function
  /// of more than one statement or without a result keeps its block.
  /// </summary>
  [TestCase("public static int F(int a, int b) => a / b;", "public static int F(int a, int b) => a / b;")]
  [TestCase("public static int F(int a, int b) => checked(a + b);", "public static int F(int a, int b) => checked(a + b);")]
  [TestCase("public static int F(int a, int b) => checked(a + unchecked(a * b));", "public static int F(int a, int b) => checked(a + unchecked(a * b));")]
  [TestCase("public static int F(int a, int b) => checked(a + b) * b;", "public static int F(int a, int b) => unchecked(checked(a + b) * b);")]
  [TestCase("public static int F(byte a, int b) => checked((byte)(a + b));", "public static int F(byte a, int b) => checked((byte)(a + b));")]
  [TestCase("public static uint F(int a, int b) => 7;", "public static uint F(int a, int b) => 7;")]
  [TestCase("public static int F(int a, int b) { a += b; return a; }", "public static int F(int a, int b) {")]
  [TestCase("public static void F(int a, int b) { }", "public static void F(int a, int b) {")]
  [TestCase("public static void F(int a, int b) { return; }", "public static void F(int a, int b) {")]
  public void ExpressionBody_IsForOneReturnedValue(string method, string expected) {
    var text = Emitted(method, "net4.6");
    Assert.That(text.Split('\n').Single(line => line.Contains(" F(")), Is.EqualTo("  " + expected));
    Assert.That(Emitted(method, "net3.5"), Does.Not.Contain("=>"));
  }

