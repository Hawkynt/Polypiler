  private (int Exit, string Output, string Error) Run(params string[] args) {
    using var output = new StringWriter();
    using var error = new StringWriter();
    var exit = new GrammarCommand(this._folder.Path).Run(args, output, error);
    return (exit, output.ToString().ReplaceLineEndings("\n"), error.ToString().ReplaceLineEndings("\n"));
  }

