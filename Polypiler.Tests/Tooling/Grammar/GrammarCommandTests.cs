  }

  /// <summary>Text helpers.</summary>
  [Test]
  public void TextHelpers_Work() {
    Assert.That((GrammarText.IsIdentifier("a_1"), GrammarText.IsIdentifier("1a"), GrammarText.IsIdentifier(""), GrammarText.IsIdentifier("a-b")), Is.EqualTo((true, false, false, false)));
    Assert.That(GrammarText.Unquote("'a\\n\\t\\'b\\\\'"), Is.EqualTo("a\n\t'b\\"));
    Assert.That(GrammarText.Unquote("'''x'''"), Is.EqualTo("x"));
    Assert.That(GrammarText.Pascal("func_type"), Is.EqualTo("FuncType"));
    Assert.That(GrammarChecker.IsTokenName("NAME_2"), Is.True);
    Assert.That(GrammarChecker.IsTokenName("_X"), Is.False);
    Assert.That(GrammarCommand.ReadTokenNames("A\n# x\n  B y\n"), Is.EquivalentTo(new[] { "A", "B" }));
    Assert.That(GrammarGenerator.IsGenerated("x\n@class A\n"), Is.True);
    Assert.That(new StringLeaf("'+'").Kind, Is.EqualTo(LiteralKind.Operator));
    Assert.That(new StringLeaf("\"m\"").Kind, Is.EqualTo(LiteralKind.SoftKeyword));
  }

