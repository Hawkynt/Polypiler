using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using Polypiler.Core;
using Polypiler.Core.Syntax;
using Polypiler.Tooling.Grammar;

namespace Polypiler.Tooling.Commands;

/// <summary>
/// <c>polypiler-tooling grammar</c> (ADR 1000): <c>generate &lt;grammar&gt; [--out &lt;file.g.cs&gt;]
/// [--namespace &lt;ns&gt;] [--class &lt;name&gt;] [--profile &lt;axis=value&gt;]...</c> writes the parser of a
/// grammar; <c>read &lt;grammar&gt; [--tokens &lt;file&gt;]</c> reads and checks a grammar and prints its
/// rules and left recursion without generating, as for CPython's own <c>python.gram</c>;
/// <c>check [--root &lt;dir&gt;]</c> regenerates every grammar that declares <c>@class</c> in memory and
/// fails on any committed file that differs, is missing or has no grammar.
/// </summary>
/// <param name="currentDirectory">What relative paths are relative to.</param>
public sealed class GrammarCommand(string currentDirectory) {

  /// <summary>The verb the command is invoked by.</summary>
  public const string Verb = "grammar";

  /// <summary>The first line of the header the generated files carry, by which the check finds them.</summary>
  public const string GeneratedHeader = "// Generated by polypiler-tooling grammar generate from ";

  private static readonly string[] _skipped = ["bin", "obj", ".git", "node_modules", "artifacts"];

  /// <summary>Creates the command for the current directory.</summary>
  public GrammarCommand()
    : this(Environment.CurrentDirectory) { }

  /// <summary>Runs the arguments that follow the verb and returns the exit code.</summary>
  public int Run(IReadOnlyList<string> args, TextWriter output, TextWriter error) {
    ArgumentNullException.ThrowIfNull(args);
    ArgumentNullException.ThrowIfNull(output);
    ArgumentNullException.ThrowIfNull(error);
    if (args.Count == 0)
      return Usage(error, "grammar needs 'generate', 'read' or 'check'");

    return args[0] switch {
      "generate" => this.Generate(args, output, error),
      "read" => this.Read(args, output, error),
      "check" => this.Check(args, output, error),
      _ => Usage(error, $"unknown grammar command '{args[0]}'")
    };
  }

  private static int Usage(TextWriter error, string message) {
    error.WriteLine($"{Program.Name}: {message}.");
    return Program.UsageError;
  }

  private static (string? Positional, Dictionary<string, List<string>> Options, string? Problem) Parse(IReadOnlyList<string> args, IReadOnlyCollection<string> known, bool positional) {
    var options = new Dictionary<string, List<string>>(StringComparer.Ordinal);
    string? file = null;
    for (var i = 1; i < args.Count; i++) {
      var arg = args[i];
      if (arg.StartsWith("--", StringComparison.Ordinal)) {
        if (!known.Contains(arg))
          return (null, options, $"unknown option '{arg}'");

        if (i + 1 == args.Count)
          return (null, options, $"option '{arg}' requires a value");

        if (!options.TryGetValue(arg, out var values))
          options[arg] = values = [];

        values.Add(args[++i]);
        continue;
      }

      if (!positional || file is not null)
        return (null, options, $"unexpected argument '{arg}'");

      file = arg;
    }

    foreach (var (option, values) in options)
      if (values.Count > 1 && option != "--profile")
        return (null, options, $"option '{option}' is given more than once");

    return (file, options, null);
  }

  private string Full(string path) => Path.GetFullPath(Path.Combine(currentDirectory, path));

  private int Generate(IReadOnlyList<string> args, TextWriter output, TextWriter error) {
    var (file, options, problem) = Parse(args, ["--out", "--namespace", "--class", "--profile"], true);
    if (problem is not null)
      return Usage(error, problem);

    if (file is null)
      return Usage(error, "grammar generate needs the grammar file");

    GrammarProfile? profile = null;
    if (options.TryGetValue("--profile", out var settings)) {
      var values = new Dictionary<string, string>(StringComparer.Ordinal);
      foreach (var setting in settings) {
        var at = setting.IndexOf('=', StringComparison.Ordinal);
        if (at <= 0)
          return Usage(error, $"'--profile {setting}' is not axis=value");

        values[setting[..at]] = setting[(at + 1)..];
      }

      profile = new(values);
    }

    var path = this.Full(file);
    if (!File.Exists(path)) {
      error.WriteLine($"{Program.Name}: grammar '{file}' does not exist.");
      return (int)ExitCode.EnvironmentError;
    }

    IReadOnlyList<GeneratedParser> parsers;
    try {
      parsers = GrammarGenerator.Generate(path, options.TryGetValue("--out", out var outFile) ? this.Full(outFile[0]) : null,
        options.TryGetValue("--namespace", out var ns) ? ns[0] : null, options.TryGetValue("--class", out var name) ? name[0] : null, profile);
    } catch (GrammarException exception) {
      foreach (var line in exception.Message.Split('\n'))
        error.WriteLine($"{Program.Name}: {line}");

      return (int)ExitCode.InvalidSource;
    }

    foreach (var parser in parsers) {
      Directory.CreateDirectory(Path.GetDirectoryName(parser.Path)!);
      File.WriteAllText(parser.Path, parser.Text);
      output.WriteLine($"wrote {Path.GetRelativePath(currentDirectory, parser.Path).Replace('\\', '/')}: {parser.Rules} rules");
    }

    return Program.Success;
  }

  private int Read(IReadOnlyList<string> args, TextWriter output, TextWriter error) {
    var (file, options, problem) = Parse(args, ["--tokens"], true);
    if (problem is not null)
      return Usage(error, problem);

    if (file is null)
      return Usage(error, "grammar read needs the grammar file");

    var path = this.Full(file);
    if (!File.Exists(path)) {
      error.WriteLine($"{Program.Name}: grammar '{file}' does not exist.");
      return (int)ExitCode.EnvironmentError;
    }

    HashSet<string>? tokens = null;
    if (options.TryGetValue("--tokens", out var tokenFile)) {
      var tokensPath = this.Full(tokenFile[0]);
      if (!File.Exists(tokensPath)) {
        error.WriteLine($"{Program.Name}: token file '{tokenFile[0]}' does not exist.");
        return (int)ExitCode.EnvironmentError;
      }

      tokens = ReadTokenNames(File.ReadAllText(tokensPath));
    }

    GrammarLoader.Loaded loaded;
    try {
      loaded = GrammarGenerator.Load(path, tokens);
    } catch (GrammarException exception) {
      foreach (var line in exception.Message.Split('\n'))
        error.WriteLine($"{Program.Name}: {line}");

      return (int)ExitCode.InvalidSource;
    }

    var rules = loaded.Grammar.Rules;
    output.WriteLine($"{Path.GetFileName(path)}: {rules.Count} rules, sha256 {loaded.Sha256}");
    output.WriteLine($"left-recursive: {string.Join(" ", rules.Where(rule => rule.LeftRecursive).Select(rule => rule.Name).Order(StringComparer.Ordinal))}");
    output.WriteLine($"leaders: {string.Join(" ", rules.Where(rule => rule.Leader).Select(rule => rule.Name).Order(StringComparer.Ordinal))}");
    return Program.Success;
  }

  /// <summary>The token names of CPython's <c>Grammar/Tokens</c>: the first word of each line that is no comment.</summary>
  /// <param name="text">The file's text.</param>
  public static HashSet<string> ReadTokenNames(string text) {
    ArgumentNullException.ThrowIfNull(text);
    var names = new HashSet<string>(StringComparer.Ordinal);
    foreach (var line in text.Split('\n')) {
      var words = line.Split((char[]?)null, StringSplitOptions.RemoveEmptyEntries);
      if (words.Length > 0 && !words[0].StartsWith('#'))
        names.Add(words[0]);
    }

    return names;
  }

  private int Check(IReadOnlyList<string> args, TextWriter output, TextWriter error) {
    var (_, options, problem) = Parse(args, ["--root"], false);
    if (problem is not null)
      return Usage(error, problem);

    var root = this.Full(options.TryGetValue("--root", out var given) ? given[0] : ".");
    if (!Directory.Exists(root)) {
      error.WriteLine($"{Program.Name}: root '{root}' does not exist.");
      return (int)ExitCode.EnvironmentError;
    }

    var problems = Drift(root);
    foreach (var line in problems)
      error.WriteLine($"{CiDiagnosticsCode}: {line}");

    output.WriteLine($"grammar check: {(problems.Count == 0 ? "every generated parser is its grammar's output" : $"{problems.Count} problems")}");
    return problems.Count == 0 ? Program.Success : Program.Failure;
  }

  /// <summary>The CI diagnostic a drifted parser is reported as.</summary>
  public const string CiDiagnosticsCode = "PLY0075";

  /// <summary>
  /// Every problem of the generated parsers below a root: a file that differs from its grammar's output
  /// (compared with LF line endings), a missing output, a grammar that does not generate, a generated
  /// file no grammar produces. Empty where everything holds.
  /// </summary>
  /// <param name="root">The repository root.</param>
  public static IReadOnlyList<string> Drift(string root) {
    ArgumentNullException.ThrowIfNull(root);
    string Relative(string path) => Path.GetRelativePath(root, path).Replace('\\', '/');
    var problems = new List<string>();
    var produced = new HashSet<string>(StringComparer.Ordinal);
    foreach (var grammar in Files(root, "*.pgram")) {
      var text = File.ReadAllText(grammar);
      if (!GrammarGenerator.IsGenerated(text))
        continue;

      IReadOnlyList<GeneratedParser> parsers;
      try {
        parsers = GrammarGenerator.Generate(grammar);
      } catch (GrammarException exception) {
        problems.Add($"{Relative(grammar)}: does not generate: {exception.Message.Split('\n')[0]}");
        continue;
      }

      foreach (var parser in parsers) {
        var target = Path.GetFullPath(parser.Path);
        produced.Add(target);
        if (!File.Exists(target))
          problems.Add($"{Relative(target)}: missing, generated from {Relative(grammar)}");
        else if (File.ReadAllText(target).ReplaceLineEndings("\n") != parser.Text)
          problems.Add($"{Relative(target)}: differs from {Relative(grammar)}");
      }
    }

    foreach (var file in Files(root, "*.g.cs"))
      if (!produced.Contains(Path.GetFullPath(file)) && File.ReadLines(file).Skip(1).FirstOrDefault()?.StartsWith(GeneratedHeader, StringComparison.Ordinal) == true)
        problems.Add($"{Relative(file)}: no grammar generates it");

    return problems;
  }

  private static IEnumerable<string> Files(string root, string pattern) {
    var pending = new Stack<string>([root]);
    var found = new List<string>();
    while (pending.Count > 0) {
      var directory = pending.Pop();
      found.AddRange(Directory.EnumerateFiles(directory, pattern));
      foreach (var child in Directory.EnumerateDirectories(directory))
        if (!_skipped.Contains(Path.GetFileName(child)))
          pending.Push(child);
    }

    found.Sort(StringComparer.Ordinal);
    return found;
  }

}
