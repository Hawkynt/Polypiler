namespace Polypiler.Core.Frontends.VBScript.Parsing;

internal enum VBScriptTokenKind {
  EndOfFile,
  NewLine,
  Colon,
  DocComment,

  // Literals & identifiers
  Identifier,
  IntLiteral,
  FloatLiteral,
  StringLiteral,

  // Punctuation & operators
  LParen,
  RParen,
  Comma,
  Dot,
  Caret,
  Star,
  Slash,
  Backslash,
  Plus,
  Minus,
  Ampersand,
  Equal,
  NotEqual,
  Less,
  LessEqual,
  Greater,
  GreaterEqual,

  // Keywords
  KwOption,
  KwExplicit,
  KwConst,
  KwDim,
  KwReDim,
  KwPreserve,
  KwPublic,
  KwPrivate,
  KwDefault,
  KwByVal,
  KwByRef,
  KwFunction,
  KwSub,
  KwProperty,
  KwGet,
  KwLet,
  KwSet,
  KwEnd,
  KwExit,
  KwCall,
  KwClass,
  KwNew,
  KwMe,
  KwIf,
  KwThen,
  KwElseIf,
  KwElse,
  KwSelect,
  KwCase,
  KwFor,
  KwTo,
  KwStep,
  KwNext,
  KwEach,
  KwIn,
  KwDo,
  KwWhile,
  KwUntil,
  KwLoop,
  KwWend,
  KwOn,
  KwError,
  KwResume,
  KwGoTo,
  KwTrue,
  KwFalse,
  KwEmpty,
  KwNull,
  KwNothing,
  KwMod,
  KwNot,
  KwAnd,
  KwOr,
  KwXor,
  KwIs,
  KwWith,
  KwErase,
  KwExecute,
  KwExecuteGlobal,
  KwEval
}

internal sealed record VBScriptToken(
  VBScriptTokenKind Kind,
  string Text,
  int Line,
  int Column,
  long LongValue = 0,
  double DoubleValue = 0.0,
  string? StringValue = null) {

  public bool IsKeyword => this.Kind >= VBScriptTokenKind.KwOption;

  public bool IsStatementTerminator => this.Kind is VBScriptTokenKind.NewLine or VBScriptTokenKind.Colon or VBScriptTokenKind.EndOfFile;

}
